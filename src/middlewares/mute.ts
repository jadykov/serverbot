/**
 * Выключатель бота в отдельно взятом разделе.
 *
 * Зачем. Топик в группе живёт своей жизнью: в одном бот нужен постоянно,
 * а в другом мешает — там люди разговаривают между собой, и лишний голос
 * ни к чему. Общего «выключить везде» для этого не годится, а лишать людей
 * бота целиком ради одного топика тем более.
 *
 * Состояние лежит в сессии, а сессия у каждого топика своя (см. getSessionKey
 * в src/bot.ts) — значит и выключатель получается на раздел сам собой,
 * без единой строчки про топики здесь.
 *
 * Права намеренно ни у кого не спрашиваются: выключить и включить может
 * любой участник. Группа маленькая и своя, договориться в ней проще, чем
 * ходить к администратору; а тот, кому бот сейчас мешает, — как раз тот,
 * кто должен уметь его унять.
 *
 * Что именно молчание останавливает: всё, кроме команды пробуждения.
 * В том числе — запись в архив поиска (middleware стоит до searchIndexer):
 * выключают бота обычно ровно затем, чтобы разговор шёл без него, и молча
 * складывать этот разговор себе в индекс было бы, мягко говоря, неожиданно.
 */
import type { MiddlewareFn } from 'grammy';
import { logger } from '../logger.js';
import { sessionKey } from '../utils.js';
import type { BotContext } from '../types.js';

/**
 * Команды, которые работают и в выключенном разделе.
 *
 * Их ровно две. «Включить» — очевидно: иначе выключенный бот было бы нечем
 * поднять. «Выключить» — потому что молчание в ответ на «выключись» читается
 * как поломка: человек не знает, что бот уже молчит, и будет повторять.
 *
 * Латинские и кириллические формы вперемешку: /stop и /start Telegram
 * размечает как команды и показывает в меню, /стоп и /старт ловятся текстом —
 * ровно та же пара, что у /gem и /гем (см. commands/ai.ts).
 */
const WAKE_WORDS = /^\/(?:start|старт|включись|stop|стоп|выключись)(?:@[A-Za-z0-9_]+)?(?:\s|$)/i;

export const mute: MiddlewareFn<BotContext> = async (ctx, next) => {
  // Апдейт без чата (а такие бывают: например, изменение прав самого бота)
  // сессии не получает вовсе, и обращение к ctx.session на нём бросает
  // исключение. Выключать в таком апдейте всё равно нечего.
  if (!sessionKey(ctx)) return next();

  if (!ctx.session.muted) return next();

  const text = ctx.message?.text ?? ctx.message?.caption ?? '';
  if (WAKE_WORDS.test(text.trim())) return next();

  /**
   * Нажатие кнопки нужно погасить ответом, а не молчанием: неотвеченный
   * callback крутит часики в клиенте, пока Telegram не сдастся сам. Человек
   * при этом видит всплывающую подсказку и понимает, что бот не сломался.
   */
  if (ctx.callbackQuery) {
    await ctx.answerCallbackQuery({
      text: 'Бот выключен в этом разделе. Включить: /start',
      show_alert: false,
    });
    return;
  }

  logger.debug('Раздел выключен, апдейт пропущен', {
    chatId: ctx.chat?.id,
    userId: ctx.from?.id,
  });
};
