/** Единая обработка ошибок нейросетей: пользователю — подсказка, в лог — детали. */
async function replyWithError(ctx: BotContext, error: unknown): Promise<void> {
  if (error instanceof ProviderNotConfiguredError) {
    await ctx.reply(
      ['🔌 Нейросеть не подключена. Чтобы включить её, добавьте ключи в .env:', '', ...error.hints.map((hint) => '• ' + hint)].join(
        '\n',
      ),
    );
    return;
  }

  if (error instanceof ProviderRequestError) {
    logger.warn('Ошибка провайдера', { provider: error.provider, message: error.message });
    await ctx.reply(`⚠️ ${error.message}`);
    return;
  }

  logger.error('Непредвиденная ошибка при обращении к нейросети', {
    error: error instanceof Error ? error.message : String(error),
  });
  await ctx.reply('😔 Что-то пошло не так. Попробуйте ещё раз чуть позже.');
}

/**
 * Отправляет ответ нейросети с разметкой.
 *
 * Модель пишет обычный Markdown, а Telegram понимает свой ограниченный
 * набор тегов — конвертируем (см. src/format.ts). Если Telegram всё же
 * не принял разметку, повторяем отправку обычным текстом: пользователь
 * должен получить ответ в любом случае.
 */
async function sendMarkdown(ctx: BotContext, markdown: string): Promise<void> {
  for (const chunk of splitMarkdown(markdown)) {
    try {
      await ctx.reply(markdownToTelegramHtml(chunk), {
        parse_mode: 'HTML',
        link_preview_options: { is_disabled: true },
      });
    } catch (error) {
      const isMarkupError =
        error instanceof GrammyError && /parse entities|unsupported start tag|can't find end/i.test(error.description);

      if (!isMarkupError) throw error;

      logger.warn('Telegram отклонил разметку, отправляю обычным текстом', {
        description: error.description,
      });
      await ctx.reply(chunk, { link_preview_options: { is_disabled: true } });
    }
  }
}

/**
 * Отрезает от истории последние N сообщений для отправки в модель.
 *
 * Тонкость: диалог обязан начинаться с реплики пользователя. Реплики
 * складываются парами, но при нечётном окне historySend оно может начаться
 * с ответа ассистента — модели семейства Gemma к такому порядку ролей
 * относятся строго и отвечают ошибкой. Лишнюю первую реплику отбрасываем.
 */
function takeHistory(history: ChatMessage[], limit: number): ChatMessage[] {
  if (limit <= 0) return [];
  const window = history.slice(-limit);
  return window[0]?.role === 'assistant' ? window.slice(1) : window;
}

/**
 * Формат авто-файла, когда его не назвали.
 *
 * Markdown, и это не по привычке: модель пишет разметкой всегда, и в .md
 * разметка остаётся разметкой — заголовки заголовками, списки списками.
 * В .txt те же символы превратились бы в мусор (его пришлось бы вычищать,
 * теряя структуру), а .html читается лучше всех, но весит втрое и правится
 * хуже. Легче .md здесь нет ничего: это тот же текст, только осмысленный.
 *
 * FILE_DEFAULT_FORMAT задаёт и его тоже, но там форматов больше, чем годится
 * для ответа: код и таблицы — это про «!файл», а не про разбор.
 */
function defaultAnswerFormat(): AnswerFormat {
  const configured = config.files.defaultFormat.toLowerCase();
  return configured === 'txt' || configured === 'html' ? configured : 'md';
}

/**
 * Отдаёт готовый ответ: одним сообщением, а не влез — целиком .md-файлом.
 *
 * Обрезать нечего и незачем: обрывать мысль на полуслове бессмысленно,
 * а просить человека повторить вопрос с нужным словом — тем более, он его
 * уже задал. Формат файла по умолчанию из настроек (.md): модель пишет
 * разметкой, и в Markdown она разметкой и остаётся.
 *
 * Влезает ли ответ, считаем тем же делителем, что и обычная отправка:
 * он умеет не рвать блок кода посередине.
 */
async function sendAnswer(ctx: BotContext, text: string, question: string): Promise<void> {
  const [first = '', ...rest] = splitMarkdown(text);

  if (rest.length === 0) {
    await sendMarkdown(ctx, first);
    return;
  }

  await sendAnswerAsFile(
    ctx,
    text,
    defaultAnswerFormat(),
    question,
    'Ответ не влез в сообщение, поэтому приехал файлом — целиком.',
  );
}

/**
 * Общий сценарий «вопрос → ответ»: идём по цепочке моделей и отвечаем первым,
 * что получилось. Если ответила не первая модель, дописываем сноску — иначе
 * непонятно, почему ответ вдруг стал другого качества.
 */
interface AskOptions {
  attachments?: Attachment[];
  /**
   * Что записать в историю вместо prompt. Нужно там, где к запросу подмешан
   * служебный контекст: цитата реплики, на которую человек ответил. В историю
   * она попасть не должна — бот и так помнит собственные слова, а дубли
   * съедают и место, и внимание модели.
   */
  historyText?: string;
  /**
   * Отдать ответ файлом, а не сообщением. Тогда же берётся файловый потолок
   * ответа — он ещё выше, чем у цепочки: файла просят как раз ради длинного
   * разбора. Сейчас этим путём идут только переросшие сообщение ответы
   * (см. sendAnswer ниже): явного слова-файла для обычного ответа больше нет.
   */
  asFile?: AnswerFormat;
  /**
   * Какой длины ждём ответ. Меняет ровно две вещи: о чём просят модель
   * и какой потолок ответа берут.
   *
   * На то, каким ответ доедет, не влияет никак: не влез в сообщение —
   * приедет файлом, и это общее правило для всего.
   */
  answerLength?: AnswerLength;
}

/**
 * `byNeed` — обычный вопрос в чат: длину модель выбирает сама, потолки
 * по токенам на уровнях остаются (не влезло в сообщение — приедет файлом).
 *
 * `detailed` — подробный разбор всегда (см. THINK_RULE). Сейчас не используется
 * ни одной командой — оставлен про запас для «!размышления».
 *
 * `unbounded` — длину диктует сама задача, и договариваться о ней не о чем:
 * дословная расшифровка голосового, заказанный файл. Правила длины не передают
 * вовсе, потолок файловый.
 */
type AnswerLength = 'byNeed' | 'detailed' | 'unbounded';

async function askChain(
  ctx: BotContext,
  provider: TextProvider,
  /** Цепочка целиком: из неё берутся и модели, и потолок ответа. */
  chain: ChainInfo,
  prompt: string,
  { attachments = [], historyText, asFile, answerLength }: AskOptions = {},
): Promise<boolean> {
  /**
   * О длине с моделью договариваются здесь только для разбора и файла;
   * обычный ответ в чат длину выбирает сам. Потолки по токенам при этом
   * остаются всегда: знаки модель не считает, и обещаниям про длину
   * верить нельзя. Что в сообщение не влезло, всё равно уедет файлом.
   *
   * Формат файла назвали, а длину не оговорили — значит её и не ограничиваем:
   * файла просят как раз ради того, что в сообщение не помещается.
   */
  const length: AnswerLength = answerLength ?? (asFile ? 'unbounded' : 'byNeed');
  const key = sessionKey(ctx);
  const speaker = authorName(ctx);
  // Долгая память раздела: короткая выжимка, которая помнит и то, что давно
  // выпало из живой истории ниже (см. src/services/digest.ts). Пустая —
  // если слияний ещё не было или память выключена.
  const digestText = key ? await getDigest(key) : '';
  const rules = [
    length === 'detailed' ? THINK_RULE : undefined,
    asFile === 'html' ? HTML_FILE_RULE : undefined,
    digestText
      ? `Вот твоя память о более ранних разговорах этого раздела — используй её, если пригодится, ` +
        `но не пересказывай целиком и не упоминай, что это «память»: ${digestText}`
      : undefined,
    `Сейчас с тобой говорит ${speaker}. Не называй людей по именам — путаешь их и обращаешься ` +
      `не к тому, к кому нужно. Обращайся без имён.`,
    META_QUESTION.test(prompt)
      ? `Похоже, тебя спрашивают про тебя самого или про твои команды. Вот точная и полная справка ` +
        `о том, что ты умеешь, — отвечай по ней, а не по догадкам, и только на то, что спросили, ` +
        `не пересказывай её целиком: ${HELP_TEXT_PLAIN}`
      : undefined,
    IDENTITY_QUESTION.test(prompt)
      ? `Тебя спрашивают, какая ты модель. Отвечай честно: ты бот «гем» — называй это имя ` +
        `и список моделей ниже, ничего не выдумывай.`
      : undefined,
  ].filter(Boolean);
  try {
    // Историю передаём укороченной, и это не то же самое, сколько её хранить:
    // в сессии лежит память раздела на дни, а модели нужен разговор, а не архив
    // (см. config.ai.historySend).
    const history = takeHistory(ctx.session.history, config.ai.historySend);

    // Двухуровневый фолбэк (п.3 плана): для умных цепочек сначала спрашиваем
    // OpenRouter (contrib→luna), при отказе всей его цепочки — Gemini-хвост.
    // Голосовая идёт только через Gemini: звук на OpenRouter не проверен.
    // Уровни собираются здесь, а не в models.ts: ChainInfo хранит один список,
    // а уровней два (провайдер+цепочка у каждого свои).
    const levels =
      chain.id === FAST_CHAIN
        ? resolveFastLevels()
        : chain.id === VOICE_CHAIN
          ? [{ provider, models: chain.models, maxOutputTokens: chain.maxOutputTokens }]
          : resolveSmartLevels(chain.models, chain.maxOutputTokens);
    // Пока модель думает, показываем «печатает…».
    // Честный список кандидатов — только здесь: уровни (а значит и модели)
    // собраны парой строк выше, в правилах выше их ещё не было.
    const candidates = [...new Set(levels.flatMap((level) => level.models))];
    const allRules = [
      ...rules,
      IDENTITY_QUESTION.test(prompt)
        ? `Модели, которые могут отвечать в этом чате: ${candidates.join(', ')}.`
        : undefined,
    ].filter(Boolean);
    const answer = await withChatAction(ctx, asFile ? 'upload_document' : 'typing', () =>
      generateWithFallback(levels, prompt, {
        history,
        attachments,
        // Потолок ответа: у цепочки свой (он упирается в минутную норму
        // её моделей), файловый ещё выше — его берут там, где длину задаёт
        // задача, а не размер сообщения. Явный потолок сильнее уровневых
        // (см. generateWithFallback): файл одинаково огромен на обоих уровнях.
        ...(asFile || length === 'unbounded' ? { maxOutputTokens: config.files.answerMaxOutputTokens } : {}),
        ...(allRules.length > 0 ? { extraInstruction: allRules.join(' ') } : {}),
      }),
    );

    if (config.ai.historyMaxTokens > 0) {
      // В историю попадает только текст: картинки повторно не пересылаются,
      // иначе каждый следующий вопрос тащил бы за собой все прежние вложения.
      // Контекст при этом не теряется — что было на снимке, модель описала
      // в своём же ответе, а он в истории есть.
      //
      // Реплику человека подписываем именем: в топике на несколько человек
      // без этого модель не различает, кто именно спросил, и не может
      // обратиться по имени (см. authorName выше).
      ctx.session.history.push(
        { role: 'user', text: `${speaker}: ${historyText ?? prompt}` },
        { role: 'assistant', text: answer.text },
      );
      // Ответы бота идут в архив поиска и в долгую память наравне с репликами
      // людей: в них половина полезного, что вообще было сказано в разделе.
      // Ссылки на них не будет — id сообщения станет известен только после
      // отправки.
      if (key) {
        rememberMessage(key, { ts: Date.now(), who: 'бот', text: answer.text });
        noteDigestMessage(key, 'бот', answer.text);
      }
      // Держим в файле сессии только живой хвост по токенному капу.
      ctx.session.history = trimHistoryByTokens(ctx.session.history, config.ai.historyMaxTokens);
    }

    if (asFile) {
      await sendAnswerAsFile(ctx, answer.text, asFile, historyText ?? prompt);
    } else {
      await sendAnswer(ctx, answer.text, historyText ?? prompt);
    }

    if (answer.skipped.length > 0) {
      await ctx.reply(
        `<i>Отвечала запасная модель <code>${escapeHtml(answer.model)}</code>: ` +
          `${answer.skipped.length === 1 ? 'основная была недоступна' : 'предыдущие были недоступны'}.</i>`,
        { parse_mode: 'HTML' },
      );
    } else if (IDENTITY_QUESTION.test(prompt)) {
      // Точное имя ответившей — только здесь: на момент сборки промпта его
      // ещё не знает никто, поэтому дописываем фактом, а не словами модели.
      await ctx.reply(`<i>Модель: <code>${escapeHtml(answer.model)}</code>.</i>`, { parse_mode: 'HTML' });
    }

    return true;
  } catch (error) {
    await replyWithError(ctx, error);
    return false;
  }
}

/**
 * Отдаёт провайдер Gemini, если он готов работать, и сам объясняет
 * пользователю причину, если нет.
 */
async function requireGemini(ctx: BotContext): Promise<TextProvider | null> {
  const gemini = findTextProvider(GEMINI_ID);

  if (!gemini) {
    await ctx.reply('⚠️ Провайдер Gemini не зарегистрирован в боте.');
    return null;
  }
  if (!gemini.isConfigured) {
    await ctx.reply(`🔌 Gemini не подключён.\n\n• ${gemini.setupHint}`);
    return null;
  }

  return gemini;
}

/** Берёт текст запроса из аргументов команды либо из сообщения, на которое ответили. */
function extractPrompt(ctx: BotContext, args: string): string {
  return args.trim() || ctx.message?.reply_to_message?.text?.trim() || '';
}

/**
 * Обработчик /гем и /gem.
 *
 * По умолчанию отвечает умная цепочка. Переключение на другие умения —
 * всегда явное, словом с восклицательным знаком.
 */
async function handleGemini(ctx: BotContext, rawPrompt: string): Promise<void> {
  const trimmed = rawPrompt.trim();

  /**
   * Реплай на фотографию. Картинки в этом сообщении нет — она в том, на которое
   * ответили, — поэтому обработчик снимков сюда не добирается, и выкачивать её
   * приходится отдельно.
   *
   * Ветка забирает и пустой запрос («/гем» реплаем на фото — «что тут?»),
   * и любой вопрос про снимок. А вот «!нарисуй», «!скажи»,
   * «!найди» пропускает дальше: они про своё, и то, что рядом
   * оказалась фотография, ничего в них не меняет.
   */
  // «!resetuser» — самой первой: она служебная, ни с чем не пересекается,
  // и реплай при ней означает «вот этот человек», а не «вот этот файл».
  const reset = RESET_PREFIX.exec(trimmed);
  if (reset) {
    await handleResetUser(ctx, reset[1] ?? '');
    return;
  }

  // «!лимиты» — тоже служебная и тоже без аргументов, реплай ей не нужен.
  if (LIMITS_PREFIX.test(trimmed)) {
    await handleLimits(ctx);
    return;
  }

  // «!личка» проверяем следующей: она про доставку уже готового сообщения,
  // и что там внутри — файл, снимок или текст — совершенно неважно. Иначе
  // реплай на документ утащил бы handleDocument, а на фото — разбор снимка.
  if (DM_PREFIX.test(trimmed)) {
    await handleSendToDm(ctx);
    return;
  }

  /**
   * Реплай на голосовое: «/гем !расшифруй» или сразу вопрос по записи —
   * «/гем что он просит сделать».
   *
   * Ветка нужна по той же причине, что и ветка реплая на фотографию: самой
   * записи в этом сообщении нет, она в том, на которое ответили, и обработчик
   * голосовых сюда не добирается. Прочие слова-переключатели пропускаем
   * дальше: «!скажи» или «!найди» рядом с голосовым — всё равно про своё.
   */
  const repliedVoice = ctx.message?.reply_to_message?.voice;
  const voiceWord = VOICE_PREFIX.exec(trimmed);
  const ownsVoice =
    repliedVoice &&
    !DRAW_PREFIX.test(trimmed) &&
    !FILE_PREFIX.test(trimmed) &&
    !SPEAK_PREFIX.test(trimmed) &&
    !SEARCH_PREFIX.test(trimmed) &&
    !WEB_PREFIX.test(trimmed) &&
    !TRACK_PREFIX.test(trimmed) &&
    !DEEP_PREFIX.test(trimmed);

  if (repliedVoice && ownsVoice) {
    // «!расшифруй выпиши дословно» — слово съедаем, остаток остаётся вопросом.
    const asked = voiceWord ? (voiceWord[1] ?? '').trim() : trimmed;
    // Голое «!расшифруй» и явные синонимы (TO_TEXT) — дословная выписка,
    // это теперь умолчание. «!расшифруй с ответом» — содержательный ответ.
    // Любой другой текст после команды — конкретный вопрос по записи, как и раньше.
    const task = WITH_ANSWER.test(asked)
      ? VOICE_DEFAULT_TASK
      : !asked || TO_TEXT.test(asked)
        ? VOICE_VERBATIM_TASK
        : asked;
    await handleVoice(ctx, repliedVoice, task);
    return;
  }

  const repliedDocument = ctx.message?.reply_to_message?.document;
  // «!сеть» реплаем на документ не ищет: поиск идёт по интернету, а не по
  // файлу, и молча разбирать документ вместо поиска — значит врать человеку
  // в лицо (он ждёт свежие данные, а получает «в файле ничего нет»).
  // Поэтому сразу объясняем, а не делаем вид, что поискали.
  if (repliedDocument && WEB_PREFIX.test(trimmed)) {
    await ctx.reply(
      '«!сеть» реплаем на файл не работает: она ищет по интернету, а не по документу.\n\n' +
        'Спросите отдельным сообщением: <code>/гем !сеть ваш вопрос</code>.',
      { parse_mode: 'HTML' },
    );
    return;
  }
  if (repliedDocument && !FILE_PREFIX.test(trimmed) && !DEEP_PREFIX.test(trimmed)) {
    await handleDocument(ctx, repliedDocument.file_id, repliedDocument.file_name ?? 'файл', `/гем ${rawPrompt}`);
    return;
  }

  const repliedPhoto = pickPhotoFileId(ctx.message?.reply_to_message?.photo ?? []);
  const ownsPhoto =
    repliedPhoto &&
    !DRAW_PREFIX.test(trimmed) &&
    !FILE_PREFIX.test(trimmed) &&
    !SPEAK_PREFIX.test(trimmed) &&
    !SEARCH_PREFIX.test(trimmed) &&
    !WEB_PREFIX.test(trimmed) &&
    !TRACK_PREFIX.test(trimmed) &&
    !DEEP_PREFIX.test(trimmed);

  if (repliedPhoto && ownsPhoto) {
    await handleRepliedPhoto(ctx, repliedPhoto, rawPrompt);
    return;
  }

  if (!rawPrompt) {
    await ctx.reply(
      'Напишите запрос после команды. Например:\n' +
        '<code>/гем объясни рекурсию за три предложения</code>\n\n' +
        'Слова с восклицательным знаком меняют поведение:\n' +
        '<code>/гем !нарисуй кота-космонавта</code> — картинка вместо текста\n' +
        '<code>/гем !скажи привет</code> — ответ голосом\n' +
        '<code>/гем !трек песня про дедлайны</code> — песня с вокалом\n' +
        '<code>/гем !найди где обсуждали деплой</code> — поиск по переписке\n' +
        '<code>/гем !сеть что нового про X</code> — поиск в интернете\n' +
        '<code>/гем !размышление что такое понимание</code> — долгое размышление\n\n' +
        'Ещё можно ответить командой <code>/гем</code> на любое сообщение — я возьму его текст, ' +
        'а если это фотография, разберу её.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  // «!расшифруй» без голосового: слушать нечего. Молча ответить текстом было бы
  // хуже всего — человек решит, что бот записи не слышит в принципе.
  if (voiceWord) {
    await ctx.reply(
      '«!расшифруй» работает по голосовому: ответьте этой командой на голосовое сообщение — ' +
        'выпишу дословно. Нужен ответ по смыслу — <code>/гем !расшифруй с ответом</code>.\n\n' +
        'В личке команда и вовсе не нужна — пришлите голосовое, и я отвечу.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  // «нарисуй» уводит запрос в совсем другую ветку — проверяем его первым.
  const draw = DRAW_PREFIX.exec(rawPrompt.trim());
  if (draw) {
    // Уточняющие вопросы задаёт бесплатный Gemini на своей лёгкой цепочке —
    // платит бот только за саму картинку (см. src/commands/draw.ts).
    try {
      await startDraw(ctx, (draw[1] ?? '').trim());
    } catch (error) {
      await replyWithError(ctx, error);
    }
    return;
  }

  const track = TRACK_PREFIX.exec(rawPrompt.trim());
  if (track) {
    await handleTrack(ctx, (track[1] ?? '').trim());
    return;
  }

  const file = FILE_PREFIX.exec(rawPrompt.trim());
  if (file) {
    await handleFile(ctx, (file[1] ?? '').trim());
    return;
  }

  const search = SEARCH_PREFIX.exec(rawPrompt.trim());
  if (search) {
    await handleSearch(ctx, (search[1] ?? '').trim());
    return;
  }

  const web = WEB_PREFIX.exec(rawPrompt.trim());
  if (web) {
    await handleWeb(ctx, (web[1] ?? '').trim());
    return;
  }

  const deep = DEEP_PREFIX.exec(rawPrompt.trim());
  if (deep) {
    await handleDeep(ctx, (deep[1] ?? '').trim());
    return;
  }

  const speak = SPEAK_PREFIX.exec(rawPrompt.trim());
  if (speak) {
    await handleSpeak(ctx, (speak[1] ?? '').trim());
    return;
  }

  const prompt = rawPrompt;

  const gemini = await requireGemini(ctx);
  if (!gemini) return;

  /**
   * Реплай на текстовое сообщение вместе со своим вопросом: «/гем как тебе
   * этот ответ?» на чужую реплику. Без этого цитируемый текст терялся бы
   * целиком — extractPrompt подставляет реплай, только если аргументов
   * не было вовсе (см. выше), а тут они есть, просто не про сам реплай.
   *
   * Реплай на фото/голос/документ сюда не долетает: у них свои ветки выше,
   * они возвращаются раньше.
   */
  const promptWithQuote = buildReplyQuotePrompt(ctx, prompt, ctx.message?.reply_to_message);

  const chain = resolveChain(SMART_CHAIN);
  // Не влезло в сообщение — приедет файлом целиком (см. sendAnswer ниже).
  const answered = await askChain(ctx, gemini, chain, promptWithQuote, {
    // В историю — чистый вопрос, без цитаты: та либо и так уже в истории
    // (если цитировали недавний ответ бота), либо разово нужна только модели.
    historyText: prompt,
  });

  // Запрос начался со слова-переключателя, но без «!». Отвечаем как на обычный
  // вопрос — человек, скорее всего, его и задавал, — но подсказываем синтаксис:
  // иначе тот, кто действительно хотел нарисовать, решит, что бот сломался.
  if (answered && FORGOTTEN_BANG.test(prompt)) {
    const word = prompt.split(/[\s,:.—–-]/)[0]!.toLowerCase();
    await ctx.reply(
      `<i>Если это была команда, а не вопрос, — она пишется с восклицательным знаком: ` +
        `<code>/гем !${escapeHtml(word)} …</code></i>`,
      { parse_mode: 'HTML' },
    );
  }
}

/**
 * Ссылка на сообщение в чате.
 *
 * У приватных супергрупп (а форум — всегда супергруппа) публичной ссылки нет,
 * но есть внутренняя: t.me/c/<id без префикса -100>/<id сообщения>. В личке
 * ссылаться не на что и незачем — там и так всё рядом.
 */
function messageLink(chatId: number, messageId: number | undefined): string | null {
  if (messageId === undefined || chatId >= 0) return null;
  return `https://t.me/c/${String(chatId).replace(/^-100/, '')}/${messageId}`;
}

/** Дата находки человеческим языком: «14 августа, 16:12». */
function formatWhen(ts: number): string {
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
    timeZone: config.imageQuota.timezone,
  }).format(new Date(ts));
}

/**
 * Поиск по переписке раздела: «/гем найди ...».
 *
 * Ищет по смыслу: «где мы обсуждали выкатку» находит разговор про деплой,
 * даже если слова «выкатка» там не было.
 */
async function handleSearch(ctx: BotContext, query: string): Promise<void> {
  if (!query) {
    await ctx.reply(
      'Напишите, что искать:\n<code>/гем найди где мы обсуждали деплой</code>\n\n' +
        'Я ищу по смыслу, а не по точным словам, и только по этому разделу.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  if (!config.search.enabled) {
    await ctx.reply('🔍 Поиск по переписке выключен (SEARCH_ENABLED=false).');
    return;
  }

  const key = sessionKey(ctx);
  if (!key) return;

  try {
    const hits = await withChatAction(ctx, 'typing', () => searchMessages(key, query));

    if (hits.length === 0) {
      await ctx.reply(
        '🔍 Ничего похожего не нашлось.\n\n' +
          '<i>Я ищу только по этому разделу и только по тому, что было сказано после ' +
          'включения поиска: задним числом переписка не индексируется.</i>',
        { parse_mode: 'HTML' },
      );
      return;
    }

    const chatId = ctx.chat?.id ?? 0;
    const lines = hits.map((hit) => {
      const link = messageLink(chatId, hit.messageId);
      const when = formatWhen(hit.ts);
      const snippet = escapeHtml(hit.text.slice(0, 300)) + (hit.text.length > 300 ? '…' : '');
      const head = link ? `<a href="${link}">${when}</a>` : when;

      return `${head}, ${escapeHtml(hit.who)}:\n${snippet}`;
    });

    await ctx.reply(`🔍 <b>Нашёл по смыслу:</b>\n\n${lines.join('\n\n')}`, {
      parse_mode: 'HTML',
      link_preview_options: { is_disabled: true },
    });
  } catch (error) {
    await replyWithError(ctx, error);
  }
}

/**
 * Правила для ответа по найденным страницам.
 *
 * Здесь единственное место, где от модели просят не краткости, а полноты,
 * и общее правило одного сообщения сюда не передают вовсе. Причина простая:
 * поиск — единственная команда с исчерпаемым запасом (кредиты Tavily, а когда
 * они кончатся — деньги на OpenRouter), и десять страниц, вычитанных ради
 * трёх строк ответа, — это выброшенный поиск. Раз уж за него заплачено,
 * пусть человек получит всё, что в найденном было.
 *
 * Потолок при этом остаётся: сообщение Telegram. Ответ метит почти в него,
 * а не за него, — файлом «!сеть» не уезжает, потому что под ответом идут
 * ссылки на источники, и в файле они теряются.
 *
 * Свой список источников модели запрещают не из вредности: бот дописывает
 * собственный, из адресов найденных страниц, и два списка подряд выглядят
 * поломкой.
 */
/**
 * Первый проход «!сеть»: чистая фактическая выжимка по найденным страницам.
 *
 * Здесь намеренно нет ни лимита длины, ни просьбы что-то домысливать —
 * это черновик для второго прохода (см. newsFinalRule), а не то, что увидит
 * человек. Разделение на два прохода на месте одного нужно ради того же,
 * зачем вообще завели «!сеть»: живой поиск — это не пересказ страниц,
 * а понимание, дополненное свежими фактами, — но эти два слоя плохо
 * получаются у модели одновременно в одном проходе: она либо держится
 * страниц и не добавляет понимания, либо начинает вплетать общие знания
 * прямо в выжимку фактов, и тогда непонятно, откуда что взялось.
 */
const NEWS_DIGEST_RULE = [
  'Это первый из двух проходов живого поиска. Разберись, что реально написано',
  'на найденных страницах, и вытащи из них фактическую выжимку — сплошную конкретику:',
  'числа, даты, названия, имена, цены, версии, условия. Свои рассуждения и общие знания',
  'без опоры на страницы не подмешивай — их добавит второй проход по этой выжимке.',
  'Если страницы противоречат друг другу — отметь это явно, а не выбирай молча одну версию.',
  'Если ответа на вопрос там нет — так и скажи, не придумывай и не добирай объём водой.',
  'Формат неважен и длина неважна: это черновик для следующего прохода, а не готовый ответ.',
].join(' ');

/** Строит запрос ко второму проходу: выжимка фактов + просьба дополнить их пониманием. */
function buildNewsFinalPrompt(query: string, digest: string): string {
  return (
    `Вопрос: ${query}\n\nСегодня ${today()}. Вот фактическая выжимка по свежим страницам ` +
    `из интернета — факты в ней уже проверены первым проходом:\n\n${digest}`
  );
}

/**
 * Второй проход «!сеть»: финальный ответ человеку по выжимке из первого прохода.
 *
 * Структура — новостная карточка под Telegram: жирный заголовок с датой,
 * лид, блок «Главное», при необходимости «Контекст». Стиль строгий,
 * «агентский»: жирный — только заголовок и названия блоков, внутри текста
 * ключевые слова подчёркиваются (++слово++ → <u>), из эмодзи — только 📰
 * в заголовке (других смайлов модель не ставит: цветные и тяжёлые).
 * Из разметки модели разрешены только **жирный**, ++подчёркивание++ и пункты
 * на ▪ (дефис тоже сойдёт — конвертер сделает из него •): решётки, таблицы,
 * цитаты и код в чате выглядят мусором, а не стилем.
 *
 * Свой список источников модели запрещают не из вредности: бот дописывает
 * собственный вторым сообщением, из адресов найденных страниц, и два списка
 * подряд выглядят поломкой.
 *
 * charBudget — потолок текста (источники едут отдельным сообщением и места
 * не занимают). Не подсказка «примерно», а число, под которое дальше жёстко
 * обрежет sendWebAnswer, если модель всё же промахнётся мимо него.
 */
function newsFinalRule(charBudget: number): string {
  const min = Math.round(charBudget * (NEWS_LENGTH_MIN_RATIO / NEWS_LENGTH_MAX_RATIO));

  return [
    'Это второй проход живого поиска. Перед тобой фактическая выжимка по свежим страницам —',
    'бери факты из неё как есть, не перепроверяй и не меняй. Твоя задача — написать по ней',
    'финальный ответ человеку, подключив свои общие знания: объясни контекст, значение',
    'и связи между фактами. В этом и смысл живого поиска — не пересказ страниц,',
    'а понимание, дополненное свежими фактами. Новых конкретных фактов — дат, чисел,',
    'имён, — которых не было в выжимке, не добавляй: общие знания это про контекст,',
    'а не про то, что можно было бы выдумать вместо поиска.',
    'Оформи ответ как карточку новостного агентства, строго в таком порядке:',
    '1) первая строка — эмодзи 📰 плюс **жирный заголовок**: суть плюс короткая дата (например, «📰 **Йошкар-Ола: перекрытия и фестиваль · 9 сентября**»);',
    '2) дальше лид — прямой ответ на вопрос в двух-трёх строках обычным текстом;',
    '3) затем строка **Главное** и 3–6 коротких пунктов, каждый с новой строки начинается с символа ▪ — по одному факту в пункте;',
    '4) если фактам нужен контекст или связь между ними — блок из строки **Контекст** и одного-двух предложений после списка.',
    'Жирный — только заголовок и слова Главное/Контекст, больше нигде. Самые ключевые слова (не больше трёх на весь ответ — имя, число, название) оберни в ++плюсы++: это подчёркивание.',
    'Других эмодзи и смайлов не ставь вовсе — только 📰 в первой строке.',
    'Разметка — только **жирный**, ++подчёркивание++ и пункты на ▪: без решёток, таблиц, цитат, кода и разделителей.',
    `Длина ответа — строго ${min}–${charBudget} знаков: это почти всё сообщение Telegram,`,
    'остаток займёт список источников, который допишет бот сам. Меньше — мало по такому',
    'объёму материала, больше не влезет в сообщение и будет обрезано.',
    'Своего списка источников не составляй и ссылки в текст не вставляй — их допишет бот.',
  ].join(' ');
}

/** Складывает найденные страницы в запрос к модели. */
function buildSearchPrompt(query: string, pages: WebPage[]): string {
  const found = pages
    .map((page, index) => `[${index + 1}] ${page.title} — ${page.url}\n${page.content}`)
    .join('\n\n');

  return `Вопрос: ${query}\n\nСегодня ${today()}. Вот что нашлось в интернете:\n\n${found}`;
}

/** Второе сообщение ответа поиска: ссылки на источники. */
function sourcesBlock(links: string[]): string {
  if (links.length === 0) return '';
  return `🔗 **Источники:**\n${links.map((link) => `▪ ${link}`).join('\n')}`;
}

/**
 * Доля от MESSAGE_LIMIT, которую должен занимать ответ «!сеть».
 *
 * Файлом такой ответ не уезжает никогда: смысл
 * живого поиска — короткая свежая выжимка в чат, а не документ на почитать.
 * Поэтому вместо запасного пути файлом здесь верхняя граница держится
 * жёстко: если модель написала больше, текст обрезается по границе абзаца
 * или предложения. Нижняя граница — это просьба к модели, а не гарантия:
 * насильно раздуть короткий честный ответ до объёма нечем.
 */
const NEWS_LENGTH_MIN_RATIO = 0.8;
const NEWS_LENGTH_MAX_RATIO = 0.9;

/** Обрезает текст по границе абзаца, а если её нет рядом — по границе предложения. */
function trimToLimit(text: string, limit: number): string {
  if (text.length <= limit) return text;

  const cut = text.slice(0, limit);
  const lastStop = Math.max(
    cut.lastIndexOf('\n\n'),
    cut.lastIndexOf('. '),
    cut.lastIndexOf('! '),
    cut.lastIndexOf('? '),
    cut.lastIndexOf('\n'),
  );

  return lastStop > limit / 2 ? cut.slice(0, lastStop + 1).trimEnd() : cut;
}

/**
 * Отправляет ответ поиска: текст — первым сообщением, список источников — вторым.
 *
 * Источники едут отдельно, а не прицепом: под них не надо вычитать место
 * из потолка текста, и вёрстка карточки не сжимается. Сам текст к этому моменту
 * уже нацелен моделью в нужный диапазон длины (см. newsFinalRule) — обрезка
 * здесь только страховка на случай, если модель попросила больше, чем ей разрешили.
 */
async function sendWebAnswer(ctx: BotContext, text: string, links: string[]): Promise<void> {
  const budget = Math.floor(MESSAGE_LIMIT * NEWS_LENGTH_MAX_RATIO);

  await sendMarkdown(ctx, trimToLimit(text, Math.max(budget, 0)));
  const sources = sourcesBlock(links);
  if (sources) await sendMarkdown(ctx, sources);
}

/** Заголовок страницы, обрезанный до разумной для ссылки длины. */
function shortTitle(title: string): string {
  return title.length > 60 ? `${title.slice(0, 57)}…` : title;
}

/** Ссылка Markdown с подписью, обрезанной до разумной длины. */
function sourceLink(title: string, url: string): string {
  // Скобки в подписи сломали бы разметку [текст](url) при разборе.
  return `[${shortTitle(title).replace(/[[\]()]/g, '')}](${url})`;
}

/**
 * Глубокое размышление: «/гем !размышление ...».
 *
 * Отличается от всего остального в боте тремя вещами сразу, и все три
 * намеренные.
 *
 * Первое — истории нет. Вопрос уходит в модель голым: ни переписки раздела,
 * ни предыдущих ответов. Не ради экономии (хотя вход и дешевеет вдесятеро),
 * а потому что с контекстом модель начинает отвечать разговору, а не вопросу,
 * — здесь же просят подумать над самим вопросом.
 *
 * Второе — ответ не попадает в историю раздела, только в архив поиска.
 * По той же причине: это законченный текст сам по себе, а не реплика,
 * к которой идут «а поподробнее?». Найти его потом «!найди» сможет.
 *
 * Третье — платит OpenRouter, а значит есть дневная норма и подпись с ценой.
 *
 * И перед самим размышлением бот идёт в Tavily за свежими страницами: знания
 * модели кончаются задолго до сегодня, а глубокое рассуждение по устаревшим
 * фактам глубоко и бесполезно разом. Поиск не удался — думаем по памяти,
 * это не повод отменять ответ; в подписи тогда честно сказано, что фактов
 * со стороны не было.
 */
async function handleDeep(ctx: BotContext, question: string): Promise<void> {
  if (!isDeepThinkConfigured()) {
    await ctx.reply(`🔌 Размышление не подключено. ${DEEP_SETUP_HINT}`);
    return;
  }

  if (!question) {
    await ctx.reply(
      'Напишите вопрос, над которым подумать:\n' +
        '<code>/гем !размышление что значит «понимать» текст</code>\n' +
        '<code>/гем !размышление стоит ли доверять интуиции в спорах</code>\n\n' +
        'Вопрос уходит без истории раздела — это разговор с чистого листа, ' +
        'зато с настоящим размышлением перед ответом. ' +
        `Платно: ${config.deepQuota.perUserPerDay} в день на человека. `,
      { parse_mode: 'HTML' },
    );
    return;
  }

  const userId = ctx.from?.id;
  const quota = await deepQuota.reserve(userId);

  if (!quota.allowed) {
    await ctx.reply(
      `🚫 На сегодня размышления закончились: ${quota.limit} в день на человека.\n\n` +
        `Норма обновится через ${quota.resetsIn}. Обычные вопросы ` +
        'работают как работали — они бесплатны.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  try {
    // Думает модель минуты, а не секунды, — предупреждаем сразу, иначе
    // молчание в ответ на заданный вопрос читается как поломка.
    const notice = await ctx.reply('🤔 Смотрю, что есть по теме, и думаю — это займёт минуту-другую…');

    // Свежие страницы: не нашлись или Tavily отказал — не беда, думаем
    // по памяти. Ради фактов отменять размышление было бы странно.
    // Профиль поиска здесь свой и щедрее, чем у «!сети»: advanced, вдвое
    // больше страниц, больше текста с каждой (см. config.openrouter.deep).
    const deep = config.openrouter.deep;
    const wanted = deep.search && isTavilyConfigured();
    const pages: WebPage[] = wanted
      ? await searchTavily(question, {
          depth: deep.searchDepth,
          maxResults: deep.searchResults,
          pageChars: deep.searchPageChars,
          autoParameters: true,
        }).catch((error) => {
          logger.warn('Свежих страниц к размышлению не будет', {
            error: error instanceof Error ? error.message : String(error),
          });
          return [];
        })
      : [];

    // Реплай на сообщение (в т.ч. на ответ самого бота) подмешивается только
    // сюда, в вопрос для модели — а не в query для Tavily выше: поиску нужны
    // чистые ключевые слова, а не «Пользователь отвечает на твою реплику…».
    const questionForModel = buildReplyQuotePrompt(ctx, question, ctx.message?.reply_to_message);
    const answer = await withChatAction(ctx, 'typing', () => thinkDeeply(questionForModel, pages));

    await ctx.api.deleteMessage(notice.chat.id, notice.message_id).catch(() => undefined);
    // Только файлом, без сопроводительного сообщения в чат (см. описание выше):
    // подпись с ценой и остатком, предупреждение об обрыве и топ-20 источников
    // дописываются внутрь .md — чат получает один файл и ничего кроме него.
    // Кап DEEP_MAX_TOKENS не трогаем, развёрнутость — на усмотрении модели.
    const price = typeof answer.costUsd === 'number' ? `$${answer.costUsd.toFixed(3)}` : 'платно';
    // Объём мыслей показываем рядом с потолком, и это не любопытство:
    // по этой паре и настраиваются DEEP_EFFORT с DEEP_MAX_TOKENS. Упёрлась
    // в потолок — есть смысл поднимать, потратила треть — незачем.
    const thoughts =
      typeof answer.thoughtTokens === 'number'
        ? `, мыслей ${answer.thoughtTokens.toLocaleString('ru')} из ${deepThoughtBudget().toLocaleString('ru')}`
        : '';

    // Оборванный ответ выглядит как законченный, просто короткий, — поэтому
    // о нём говорят прямо и говорят, что делать: спросить уже, а не поднимать
    // потолок ради одного случая.
    const cut = answer.truncated
      ? '\n\n⚠️ Место кончилось раньше мысли: ответ оборван. Спросите то же самое уже — ' +
        'по одному дню, по одному пункту, — или поднимите DEEP_MAX_TOKENS.'
      : '';

    const grounded = pages.length > 0 ? `, страниц ${pages.length}` : ', без свежих страниц';
    const footer =
      `\n\n---\n\n*Думала \`${answer.model}\`, ${Math.round(answer.elapsedMs / 1000)} с${thoughts}${grounded}, ${price}. ` +
      `Осталось на сегодня: ${quota.remaining} из ${quota.limit}.*${cut}`;

    // Топ-20 источников — внутрь файла, а не в чат: ответ уезжает .md всегда,
    // и ссылки нужны там же, где текст, а не отдельным сообщением.
    const sourcesSection =
      pages.length > 0
        ? `\n\n## Источники\n${pages
            .slice(0, 20)
            .map((page, index) => `${index + 1}. ${sourceLink(page.title, page.url)}`)
            .join('\n')}`
        : '';

    // Всегда файлом, а не по длине (см. sendAnswer): в этом и смысл команды —
    // развёрнутый разбор, а не сообщение, обрезанное под лимит Telegram.
    await sendAnswerAsFile(ctx, answer.text + footer + sourcesSection, 'md', question);

    // В архив поиска — да, в историю раздела — нет (см. описание выше).
    const key = sessionKey(ctx);
    if (key) rememberMessage(key, { ts: Date.now(), who: 'бот', text: answer.text });
  } catch (error) {
    // Норма — про полученные ответы, а не про попытки.
    await deepQuota.release(userId);
    await replyWithError(ctx, error);
  }
}

/**
 * Живой поиск: «/гем !сеть ...».
 *
  * Только Tavily: он отдаёт страницы, а ответ по ним пишут web-уровни
  * (L1 contrib→luna, L2 Gemini-хвост — см. resolveWebLevels). Денег это не стоит вовсе —
 * тратится кредит из пакета и бесплатная норма Google, а разбор пяти
 * найденных страниц как раз тот случай, где голова помощнее не лишняя.
 *
 * Платный запасной путь через плагин OpenRouter (services/openrouter-web.ts)
 * пока отключён — модуль остался в коде, но handleWeb его не вызывает.
 */
async function handleWeb(ctx: BotContext, query: string): Promise<void> {
  if (!isTavilyConfigured()) {
    await ctx.reply(`🔌 Живой поиск не подключён. ${TAVILY_SETUP_HINT}`);
    return;
  }

  if (!query) {
    await ctx.reply(
      'Напишите, что узнать в интернете:\n' +
        '<code>/гем !сеть что нового про Gemini 3</code>\n' +
        '<code>/гем !сеть какая погода в Москве</code>\n\n' +
        `Норма — ${config.webQuota.perUserPerDay} поисков в день на человека. ` +
        'Поиск по нашей же переписке — другая команда: <code>/гем !найди …</code>',
      { parse_mode: 'HTML' },
    );
    return;
  }

  const userId = ctx.from?.id;
  const quota = await webQuota.reserve(userId);

  if (!quota.allowed) {
    await ctx.reply(
      `🚫 На сегодня поиски закончились: ${quota.limit} в день на человека.\n\n` +
        `Норма обновится через ${quota.resetsIn}. Обычные вопросы и поиск по переписке ` +
        'работают как работали — они бесплатны.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  try {
    const answered = await withChatAction(ctx, 'typing', () => searchWithTavily(ctx, query));

    // Ответить не вышло — ничего не нашлось или Gemini не подключён,
    // сообщение об этом уже ушло пользователю. Слот нормы возвращаем:
    // она про полученные ответы.
    if (answered === null) {
      await webQuota.release(userId);
      return;
    }

    if (config.ai.historyMaxTokens > 0) {
      ctx.session.history.push({ role: 'user', text: query }, { role: 'assistant', text: answered });
      const key = sessionKey(ctx);
      if (key) rememberMessage(key, { ts: Date.now(), who: 'бот', text: answered });
      ctx.session.history = trimHistoryByTokens(ctx.session.history, config.ai.historyMaxTokens);
    }
  } catch (error) {
    // Норма — про потраченное, а не про попытки: неудачный поиск слот вернёт.
    await webQuota.release(userId);
    await replyWithError(ctx, error);
  }
}

/**
 * Страницы от Tavily, ответ пишут web-уровни: L1 luna, L2 Gemini-хвост.
 *
 * Возвращает null, если ответить не вышло — ничего не нашлось или ни один
 * текстовый провайдер не настроен; в обоих случаях сообщение об этом уже
 * ушло пользователю.
 *
 * Глубина и число страниц — умолчания Tavily (basic, 1 кредит; 5 страниц):
 * раньше здесь стояли advanced и 8 страниц ради более точной выдачи, но
 * 31.08.2026 на боте это стабильно ловило таймаут первого прохода («выжимка
 * фактов» разбирает страницы — см. NEWS_DIGEST_RULE): 28КБ текста от 8 страниц
 * не укладывались в 150с у gemini-3.5-flash, а таймаут цепочка не перебирает
 * (см. RETRYABLE в chain.ts), так что запрос падал целиком. Меньше страниц —
 * меньше веса на входе первого прохода и меньше риск не уложиться.
 */
async function searchWithTavily(ctx: BotContext, query: string): Promise<string | null> {
  const pages = await searchTavily(query);

  if (pages.length === 0) {
    await ctx.reply(
      '🔍 В интернете ничего подходящего не нашлось.\n\n' +
        '<i>Попробуйте переформулировать — поиск понимает обычные слова, ' +
        'а не только точные названия.</i>',
      { parse_mode: 'HTML' },
    );
    return null;
  }

  // Web-уровни (см. resolveWebLevels в services/registry.ts): L1 contrib→luna,
  // L2 Gemini-хвост. Модели и потолок берём у main-хвоста как запасной список.
  const levels = resolveWebLevels(config.gemini.chains.main);
  if (levels.length === 0) {
    await ctx.reply('🔌 Живой поиск не подключён: нет ни OpenRouter-ключа, ни Gemini-ключа.');
    return null;
  }

  // Реплай на сообщение (в т.ч. на ответ самого бота) подмешивается только
  // в промпты модели ниже — не в query выше, тому нужны чистые
  // ключевые слова для Tavily, а не цитата с обвязкой.
  const topic = buildReplyQuotePrompt(ctx, query, ctx.message?.reply_to_message);

  // Первый проход: чистая фактическая выжимка по найденным страницам,
  // без своих рассуждений (см. NEWS_DIGEST_RULE). Вход — ~8000 токенов
  // (5 страниц по 4000 знаков), отсюда и потолок 4000: выжимке нужно место
  // развернуться, а резать её — терять факты.
  //
  // При отказе kind=timeout повторяем ОДИН раз на следующем уровне из
  // переупорядоченного списка (levels.slice(1)): обычно это значит «луна
  // не ответила — спросить Gemini-хвост». Худший случай — 240 с (два таймаута
  // по 120 с), но луна отвечает ~1 с, так что ретрай — только страховка
  // от разового зависания. Глобальный RETRYABLE не трогаем: там таймаут
  // неперебираемый сознательно, второй проход не ретраим тоже.
  let digest;
  try {
    digest = await generateWithFallback(levels, buildSearchPrompt(topic, pages), {
      maxOutputTokens: config.ai.webDigestMaxOutputTokens,
      extraInstruction: NEWS_DIGEST_RULE,
      // Свой таймаут: см. config.ai.webTimeoutMs — запрос сюда тяжелее обычного.
      timeoutMs: config.ai.webTimeoutMs,
    });
  } catch (error) {
    const timedOut = error instanceof ProviderRequestError && error.kind === 'timeout';
    if (!timedOut || levels.length < 2) throw error;
    logger.warn('Первый проход «!сети» упёрся в таймаут, повторяю раз на следующем уровне', {
      levels: levels.length,
    });
    digest = await generateWithFallback(levels.slice(1), buildSearchPrompt(topic, pages), {
      maxOutputTokens: config.ai.webDigestMaxOutputTokens,
      extraInstruction: NEWS_DIGEST_RULE,
      timeoutMs: config.ai.webTimeoutMs,
    });
  }

  const links = pages.slice(0, 5).map((page) => sourceLink(page.title, page.url));
  // Источники едут отдельным сообщением (см. sendWebAnswer) — второй проход
  // целится в MESSAGE_LIMIT целиком, вычитать под них ничего не надо.
  const charBudget = Math.floor(MESSAGE_LIMIT * NEWS_LENGTH_MAX_RATIO);

  // Второй проход: финальный ответ по выжимке, дополненный пониманием, —
  // в этом смысл живого поиска (см. newsFinalRule). Потолок — одно сообщение
  // Telegram минус запас (WEB_FINAL_MAX_OUTPUT_TOKENS), но не ниже
  // OPENROUTER_OUTPUT_FLOOR: contrib с меньшим отдаёт огрызок вместо ответа
  // (рассуждения съедают весь лимит — 2026-09-09 финал с 1400 вернулся
  // обрывком «**Глав»). Gemini-уровень больший потолок не выбирает: его
  // держат просьба о длине в newsFinalRule и обрезка в sendWebAnswer.
  const answer = await generateWithFallback(levels, buildNewsFinalPrompt(topic, digest.text), {
    maxOutputTokens: Math.max(config.ai.webFinalMaxOutputTokens, OPENROUTER_OUTPUT_FLOOR),
    extraInstruction: newsFinalRule(Math.max(charBudget, 0)),
    timeoutMs: config.ai.webTimeoutMs,
  });

  await sendWebAnswer(ctx, answer.text, links);

  logger.info('Ответ с поиском отправлен', { model: answer.model, pages: pages.length });
  return answer.text;
}

/**
 * Обрезает текст до разумной длины по границе предложения.
 *
 * Резать на полуслове неприятно на слух: голос обрывается посреди фразы,
 * и непонятно, кончилась мысль или сломался бот.
 */
function trimForSpeech(text: string, limit: number): { text: string; trimmed: boolean } {
  if (text.length <= limit) return { text, trimmed: false };

  const cut = text.slice(0, limit);
  const lastStop = Math.max(cut.lastIndexOf('. '), cut.lastIndexOf('! '), cut.lastIndexOf('? '), cut.lastIndexOf('\n'));

  return { text: lastStop > limit / 3 ? cut.slice(0, lastStop + 1) : cut, trimmed: true };
}

/**
 * «/гем !resetuser …» — обнулить человеку дневные нормы. Только для админов.
 *
 * Сбрасываются все шесть разом (картинки, треки, поиск, размышления,
 * озвучка, сообщения), и это
 * не лень: сбрасывают норму не «по бухгалтерии», а потому что человеку нужно
 * доделать начатое, и выяснять при этом, какая именно норма кончилась, —
 * лишний ход. Что было потрачено, бот в ответе покажет.
 */
async function handleResetUser(ctx: BotContext, target: string): Promise<void> {
  // Не «доступ запрещён», а ровное объяснение: команда служебная, и человек,
  // набравший её из любопытства, не сделал ничего плохого.
  if (!isAdmin(ctx.from?.id)) {
    await ctx.reply('Это служебная команда: сбрасывать нормы может только тот, кто платит по счёту.');
    return;
  }

  const asked = target.trim();
  const replied = ctx.message?.reply_to_message?.from;

  /** Кого сбрасываем: id и как его назвать в ответе. */
  let userId: number | undefined;
  let who = '';

  if (asked.toLowerCase() === 'self') {
    userId = ctx.from?.id;
    who = 'вам';
  } else if (!asked && replied && !replied.is_bot) {
    userId = replied.id;
    who = replied.username ? `@${replied.username}` : replied.first_name || String(replied.id);
  } else if (/^\d+$/.test(asked)) {
    userId = Number(asked);
    who = `id ${asked}`;
  } else if (asked) {
    const found = await findUser(asked);
    if (!found) {
      // Метода «найди человека по нику» в Bot API нет вовсе, и это не наша
      // недоработка: бот знает только тех, кого слышал. Поэтому не «нет
      // такого пользователя», а «я его пока не слышал», — разница важная.
      await ctx.reply(
        `Ника <code>${escapeHtml(asked.replace(/^@/, ''))}</code> в справочнике нет: ` +
          'по нику я узнаю только тех, кто писал в чат при мне ' +
          `(сейчас таких ${await knownUsers()}). ` +
          'Ответьте <code>!resetuser</code> реплаем на его сообщение — так сработает всегда, — ' +
          'или дайте числовой id, его показывает /whoami.',
        { parse_mode: 'HTML' },
      );
      return;
    }
    userId = found.id;
    who = found.name ? `${found.name} (@${asked.replace(/^@/, '')})` : `@${asked.replace(/^@/, '')}`;
  }

  if (userId === undefined) {
    await ctx.reply(
      'Кому сбросить нормы:\n' +
        '<code>/гем !resetuser self</code> — себе\n' +
        '<code>/гем !resetuser @ник</code> — по нику\n' +
        '<code>/гем !resetuser</code> реплаем на сообщение — его автору',
      { parse_mode: 'HTML' },
    );
    return;
  }

  const spent = await resetEveryQuota(userId);

  logger.info('Нормы сброшены вручную', { by: ctx.from?.id, userId, spent });

  await ctx.reply(
    spent.length > 0
      ? `♻️ Нормы сброшены ${who}: было потрачено ${spent.join(', ')}. Все шесть снова полные.`
      : `♻️ Сбрасывать ${who} было нечего — сегодня ни одна норма не тронута.`,
  );
}

/**
 * «/гем !лимиты» — сколько осталось сегодня от показанных дневных норм.
 *
 * Порядок — от самой щедрой нормы к самой строгой: поиск в интернете,
 * озвучка, размышление, картинки, треки (см. src/config.ts).
 * peek() ничего не тратит, только подсматривает — этим и отличается
 * от reserve() в остальных обработчиках.
 */
async function handleLimits(ctx: BotContext): Promise<void> {
  const userId = ctx.from?.id;
  if (userId === undefined) {
    await ctx.reply('Не вижу, кто спрашивает, — напишите от своего имени.');
    return;
  }

  const items: Array<{ icon: string; label: string; quota: DailyQuota }> = [
    { icon: '🌐', label: 'Поиск в интернете', quota: webQuota },
    { icon: '🔊', label: 'Озвучка', quota: ttsQuota },
    { icon: '🧠', label: 'Размышление', quota: deepQuota },
    { icon: '🎨', label: 'Картинки', quota: imageQuota },
    { icon: '🎵', label: 'Треки', quota: trackQuota },
  ];

  const rows = await Promise.all(
    items.map(async ({ icon, label, quota }) => {
      const peeked = await quota.peek(userId);
      if (!peeked) return `${icon} ${label}: без нормы`;
      const left = Math.max(0, peeked.limit - peeked.used);
      return `${icon} ${label}: ${peeked.used}/${peeked.limit}, осталось ${left}, сброс через ${peeked.resetsIn}`;
    }),
  );

  await ctx.reply(['📊 <b>Ваши лимиты на сегодня</b>', '', ...rows].join('\n'), { parse_mode: 'HTML' });
}

/**
 * «/гем !личка» реплаем — копия сообщения уезжает в личный диалог с ботом.
 *
 * Копируем, а не пересылаем: forward тащит за собой шапку «переслано из…»
 * и ссылку на закрытую группу, которая у получателя всё равно не откроется.
 * copyMessage делает самостоятельную копию — с файлом, подписью и разметкой,
 * но без хвоста. Файл при этом не перезаливается: Telegram копирует его
 * у себя, поэтому даже тяжёлый документ уходит мгновенно.
 */
async function handleSendToDm(ctx: BotContext): Promise<void> {
  const userId = ctx.from?.id;
  const chat = ctx.chat;
  const target = ctx.message?.reply_to_message;

  if (!userId || !chat) return;

  if (chat.type === 'private') {
    await ctx.reply('Мы и так в личном диалоге — пересылать некуда.');
    return;
  }

  if (!target) {
    await ctx.reply(
      'Ответьте <code>/гем !личка</code> на сообщение, которое нужно забрать себе — ' +
        'файл, снимок или обычный текст.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  try {
    await ctx.api.copyMessage(userId, chat.id, target.message_id);
    await ctx.reply('📨 Отправил вам в личные сообщения.');
    logger.info('Сообщение скопировано в личку', { userId, from: chat.id, message: target.message_id });
  } catch (error) {
    // 403 — единственная осмысленная ошибка здесь: человек не открывал
    // с ботом личный диалог, а первым бот написать не может.
    if (error instanceof GrammyError && error.error_code === 403) {
      const link = ctx.me?.username ? `https://t.me/${ctx.me.username}` : 'диалог с ботом';
      await ctx.reply(
        `Сначала откройте со мной личный диалог и нажмите «Запустить»: ${link}\n` +
          'После этого повторите — перешлю.',
        { link_preview_options: { is_disabled: true } },
      );
      return;
    }

    logger.warn('Не удалось скопировать сообщение в личку', {
      error: error instanceof Error ? error.message : String(error),
    });
    await ctx.reply('⚠️ Не получилось переслать. Попробуйте ещё раз или сохраните файл прямо отсюда.');
  }
}

/**
 * Озвучка: «/гем скажи ...».
 *
 * Без текста берётся последний ответ бота из истории раздела — обычно
 * человек как раз его и хочет послушать, а переписывать его руками глупо.
 */
/**
 * Заказ голоса перед текстом: «/гем !скажи «низкий» привет, коллеги».
 *
 * Кавычки — быстрый и бесплатный путь, не единственный. Без них не отличить
 * голос от речи чисто по тексту: «!скажи низкий поклон всем» — с виду то ли
 * просьба прочитать фразу про поклон, то ли прочитать «поклон всем» низким
 * голосом. Кавычки снимают эту неоднозначность мгновенно, без обращения
 * к модели, — годятся любые, какие поставит клавиатура: «ёлочки», "прямые",
 * 'одинарные'. Без кавычек ту же неоднозначность распутывает planSpeech
 * (см. src/services/gemini-tts.ts) — тем же смыслом, но с одним лишним
 * запросом к лёгкой модели.
 */
const VOICE_SPEC = /^\s*[«"'“]([^«»"'”]{1,60})[»"'”]\s*([\s\S]*)$/;

async function handleSpeak(ctx: BotContext, request: string): Promise<void> {
  // Голос и манера, если их заказали кавычками в начале.
  const spec = VOICE_SPEC.exec(request);
  let voiceRequest: VoiceRequest = spec ? parseVoiceRequest(spec[1] ?? '') : {};
  const asked = spec ? (spec[2] ?? '').trim() : request;
  // Для подписи к озвучке: что именно попросили — из кавычек или из свободного разбора ниже.
  let directionNote = spec ? spec[1] : '';

  // Что озвучивать, по убыванию определённости:
  //   1. текст после «!скажи» — сказано прямо, спорить не о чем;
  //   2. сообщение, на которое ответили реплаем, — показано пальцем.
  //      Причём любое, не только своё: попросить озвучить чужую реплику
  //      так же естественно, как свою;
  //   3. последний ответ бота в разделе — «прочитай, что ты там написал».
  const replyTo = ctx.message?.reply_to_message;
  const quoted = (replyTo?.text ?? replyTo?.caption ?? '').trim();
  const lastAnswer = [...ctx.session.history].reverse().find((message) => message.role === 'assistant')?.text;
  const source = asked || quoted || lastAnswer || '';

  if (!source) {
    await ctx.reply(
      'Напишите, что произнести:\n<code>/гем !скажи привет, коллеги</code>\n\n' +
        'Голос и манеру можно попросить прямо своими словами:\n' +
        '<code>/гем !скажи низким голосом, испуганным шёпотом: они уже близко</code>\n\n' +
        `Готовые голоса: ${listVoiceNames().join(', ')}. ` +
        'Манеру можно просить какую угодно: шёпотом, устало, торжественно. ' +
        'Пол сам манерой не считается — его нужно назвать словом «мужской» или «женский».\n\n' +
        'Или ответьте этой командой на сообщение — озвучу его. Без того и другого ' +
        'я читаю свой последний ответ, но в этом разделе я ещё ничего не отвечал.',
      { parse_mode: 'HTML' },
    );
    return;
  }

  let spoken = source;

  // Без кавычек, но с текстом прямо после «!скажи» — просим лёгкую модель
  // отделить голос и манеру от самой фразы её собственными словами, а дальше
  // эти слова идут через тот же parseVoiceRequest, что и для кавычек: разбор
  // остаётся одним и тем же, меняется только то, откуда берутся слова.
  //
  // Реплай передаём как контекст, а не как готовый ответ: «!скажи голосом
  // старого деда» ответом на чужую реплику целиком состоит из указания
  // голоса — озвучивать в буквальном смысле нечего, если не показать
  // помощнику, что именно есть под рукой. planSpeech сам решит, что из
  // asked — направление, а что, если вообще есть, — текст поверх контекста.
  if (!spec && asked) {
    const levels = resolveFastLevels();
    if (levels.length > 0) {
      const plan = await withChatAction(ctx, 'typing', () => planSpeech(levels, asked, quoted || undefined));
      spoken = plan.text;
      if (plan.direction) {
        voiceRequest = parseVoiceRequest(plan.direction);
        directionNote = plan.direction;
      }
    }
  }

  // Разметка Markdown на слух превращается в мусор: «звёздочка жирный звёздочка».
  const plain = spoken.replace(/[*_`#>]/g, '').replace(/\[([^\]]+)]\([^)]+\)/g, '$1');
  const { text, trimmed } = trimForSpeech(plain.trim(), config.tts.maxChars);

  // Норма — на готовую озвучку, а не на разбор просьбы выше: planSpeech идёт
  // по бесплатному Gemini, а платится синтез. Поэтому занимаем слот здесь,
  // а не в начале — как у треков (см. handleTrack).
  const speakUserId = ctx.from?.id;
  const speakQuota = await ttsQuota.reserve(speakUserId);
  if (!speakQuota.allowed) {
    await ctx.reply(
      `🚫 На сегодня озвучки закончились: ${speakQuota.limit} в день на человека.\n\n` +
        `Норма обновится через ${speakQuota.resetsIn}.`,
      { parse_mode: 'HTML' },
    );
    return;
  }

  try {
    const speech = await withChatAction(ctx, 'record_voice', () => synthesizeSpeech(text, voiceRequest));

    // Итоговый голос — тот, что реально пошёл в синтез (заказ или дефолт из
    // настроек, если своего не назвали): фолбэк request.voice ?? config.tts.voice
    // живёт внутри synthesizeSpeech, наружу возвращается только запись.
    const finalVoice = voiceRequest.voice ?? config.tts.voice;
    const notes = [
      directionNote ? `голос: ${directionNote} → ${finalVoice}` : `голос: ${finalVoice}`,
      speech.skipped.length > 0 ? 'озвучивала запасная модель' : '',
      trimmed ? `прочитано ${text.length} знаков из ${plain.length}` : '',
    ].filter(Boolean);
    const caption = notes.length > 0 ? `🔊 ${notes.join(', ')}` : undefined;

    // Настоящее голосовое Telegram принимает только в OGG/Opus. Без ffmpeg
    // отдаём WAV обычным аудиофайлом — играется так же, выглядит иначе.
    if (speech.isVoice) {
      await ctx.replyWithVoice(new InputFile(speech.data, 'speech.ogg'), caption ? { caption } : {});
    } else {
      await ctx.replyWithAudio(new InputFile(speech.data, 'speech.wav'), {
        title: 'Озвучка',
        ...(caption ? { caption } : {}),
      });
    }
  } catch (error) {
    // Норма — про полученные озвучки, а не про попытки.
    await ttsQuota.release(speakUserId);
    await replyWithError(ctx, error);
  }
}

/**
 * Песня с вокалом: «/гем !трек ...».
 *
 * Устроено в два шага, и первый из них бесплатный. Ace-Step ждёт не просьбу
 * словами, а стиль тегами по-английски и отдельно слова песни с разметкой
 * структуры — это собирает Gemini на лёгкой цепочке (см. services/song-prompt.ts).
 * Только потом заказывается сам трек, и вот он стоит денег: платится секунда
 * готового звука, минута — около трёх центов.
 *
 * Отсюда порядок проверок: сперва ключ, потом замысел, потом бесплатный
 * черновик, и лишь затем дневная норма и заказ. Занимать слот нормы раньше
 * значит списать его за неудавшийся черновик, а он не стоил ничего.
 *
 * Деньги тратятся только по кнопке «Заказать» под показанными словами —
 * как подтверждение «Рисовать» у картинок (см. src/commands/draw.ts):
 * черновик лежит в сессии раздела (по одному на человека, TTL те же 30 минут),
 * слот нормы занимается лишь по нажатию. Слова человек видит заранее и может
 * отменить заказ, ничего не потратив. Без вокала слов нет — кнопка всё равно
 * нужна: длительность и стиль тоже стоит подтвердить.
 */
/**
 * Убирает служебные теги структуры песни ([verse], [chorus], [bridge], ...)
 * из текста, который видит человек в чате, — оставляя саму разметку как
 * границы абзацев. Ace-Step эти теги требуются буквально в тексте (см.
 * planSong в services/song-prompt.ts), а читателю в Telegram они не нужны:
 * ни один человек не подпевает по строке «[chorus]».
 */
function humanizeLyrics(lyrics: string): string {
  return lyrics
    .split(/\[[a-zа-яё]+\]/gi)
    .map((block) => block.trim())
    .filter(Boolean)
    .join('\n\n');
}

async function handleTrack(ctx: BotContext, request: string): Promise<void> {
  if (!isMusicConfigured()) {
    await ctx.reply(`🔌 Музыка не подключена. ${MUSIC_SETUP_HINT}`);
    return;
  }

  if (!request) {
    await ctx.reply(
      'Опишите песню после «!трек». Например:\n' +
        '<code>/гем !трек грустная песня про дедлайны, женский вокал</code>\n' +
        '<code>/гем !трек полминуты весёлого чиптюна без вокала</code>\n\n' +
        'Реплаем на сообщение — песня будет про него: ' +
        '<code>/гем !трек песня о ситуации</code> ответом на чужую реплику.\n\n' +
        `Стиль и слова я соберу сам. Длительность можно назвать словами («секунд десять») — ` +
        (config.goapi.music.duration === config.goapi.music.maxDuration
          ? `по умолчанию и максимум ${config.goapi.music.duration} с. `
          : `по умолчанию ${config.goapi.music.duration} с, максимум ${config.goapi.music.maxDuration} с. `) +
        `Это платно: ${config.trackQuota.perUserPerDay} трека в день на человека.`,
      { parse_mode: 'HTML' },
    );
    return;
  }

  const gemini = await requireGemini(ctx);
  if (!gemini) return;

  // Реплай на сообщение — «!трек песня о ситуации» — даёт сюжет песни:
  // без этого написать про «ситуацию» решительно не из чего.
  const replyTo = ctx.message?.reply_to_message;
  const situation = (replyTo?.text ?? replyTo?.caption ?? '').trim() || undefined;

  // Шаг бесплатный: стиль по-английски, слова песни и длительность.
  const plan = await withChatAction(ctx, 'typing', () => planSong(resolveFastLevels(), request, situation));

  if (!plan) {
    await ctx.reply(
      '😕 Не получилось собрать песню из этого замысла — помощник не вернул ни стиля, ни слов.\n\n' +
        'Попробуйте сказать конкретнее: жанр, настроение, о чём поётся. ' +
        'Денег это не стоило — трек ещё не заказывался.',
    );
    return;
  }

  const duration = clampDuration(plan.duration);
  const instrumental = isInstrumental(plan);
  const title = plan.title || request.slice(0, 60);

  /**
   * Теги структуры ([verse], [chorus], [bridge]) убираем из того, что видит
   * человек и что уходит в саму генерацию (подробно — см. комментарий
   * в orderTrack ниже: модель их, похоже, поёт как есть на русских словах).
   */
  const lyrics = instrumental ? plan.lyrics : humanizeLyrics(plan.lyrics);

  // План показан — заказ только по кнопке. Черновик в сессии, слот нормы
  // ещё не занят: отмена ничего не стоит по построению.
  setTrackDraft(ctx, {
    title,
    stylePrompt: plan.stylePrompt,
    ...(plan.negativeStylePrompt ? { negativeStylePrompt: plan.negativeStylePrompt } : {}),
    lyrics,
    duration,
    instrumental,
  });
  await ctx.reply(await trackConfirmText(ctx, getTrackDraft(ctx)!, false), {
    parse_mode: 'HTML',
    reply_markup: trackConfirmKeyboard(),
  });
}

/** Достаёт черновики треков раздела, попутно выбрасывая протухшие (TTL — тот же, что у рисования). */
function trackDrafts(ctx: BotContext): Record<string, TrackDraft> {
  const all = ctx.session.trackDrafts ?? {};
  const deadline = Date.now() - config.draw.draftTtlMin * 60 * 1000;

  for (const [userId, draft] of Object.entries(all)) {
    if (draft.updatedAt < deadline) delete all[userId];
  }

  ctx.session.trackDrafts = all;
  return all;
}

function getTrackDraft(ctx: BotContext): TrackDraft | undefined {
  const userId = ctx.from?.id;
  return userId === undefined ? undefined : trackDrafts(ctx)[String(userId)];
}

function setTrackDraft(ctx: BotContext, draft: Omit<TrackDraft, 'updatedAt'>): void {
  const userId = ctx.from?.id;
  if (userId === undefined) return;
  trackDrafts(ctx)[String(userId)] = { ...draft, updatedAt: Date.now() };
}

function clearTrackDraft(ctx: BotContext): void {
  const userId = ctx.from?.id;
  if (userId !== undefined) delete trackDrafts(ctx)[String(userId)];
}

/** Клавиатура подтверждения заказа: деньги — только по «Заказать». */
function trackConfirmKeyboard(): InlineKeyboard {
  return new InlineKeyboard().text('🎵 Заказать', `${TRACK_CB}:go`).row().text('✖️ Отмена', `${TRACK_CB}:cancel`);
}

/**
 * Слова для показа в чате. У подписей к аудио лимит 1024 знака, а слов
 * всё равно захотят прочесть — поэтому они идут отдельным сообщением,
 * которое заодно и подтверждение заказа.
 *
 * Порядок «сначала обрезать, потом экранировать» существенен. Наоборот
 * — значит однажды разрезать сущность пополам: «&amp;» превращается
 * в «&am», Telegram отвечает «can't parse entities», и человек не получает
 * ни слов, ни трека.
 */
function trackLyricsBlock(draft: TrackDraft): string {
  return draft.instrumental ? '<i>Без вокала.</i>' : escapeHtml(draft.lyrics.slice(0, 3000));
}

/** Текст подтверждения: что закажем, почём и сколько останется на сегодня. */
async function trackConfirmText(ctx: BotContext, draft: TrackDraft, writing: boolean): Promise<string> {
  const quota = await trackQuota.peek(ctx.from?.id);
  const left = quota ? `\nОстанется на сегодня: ${Math.max(0, quota.limit - quota.used - 1)} из ${quota.limit}` : '';
  const cost = `~${draft.duration} с, ~$${(draft.duration * config.goapi.music.pricePerSecondUsd).toFixed(3)}${left}`;

  return [
    `🎵 <b>${escapeHtml(draft.title)}</b>`,
    '',
    `<i>${escapeHtml(draft.stylePrompt)}</i>`,
    `<i>${cost}</i>`,
    '',
    trackLyricsBlock(draft),
    ...(writing ? ['', '<i>Пишу…</i>'] : []),
  ].join('\n');
}

/**
 * Единственное место, где тратятся деньги на музыку.
 *
 * Слот дневной нормы занимается до вызова и возвращается при неудаче:
 * генерация идёт десятки секунд, за это время можно нажать кнопку ещё раз.
 */
async function orderTrack(ctx: BotContext, draft: TrackDraft): Promise<void> {
  const userId = ctx.from?.id;
  const quota = await trackQuota.reserve(userId);

  if (!quota.allowed) {
    clearTrackDraft(ctx);
    await ctx.reply(
      `🚫 На сегодня треки закончились: ${quota.limit} в день на человека — музыка стоит денег.\n\n` +
        `Норма обновится через ${quota.resetsIn}. Текст песни, если он нужен, я напишу и без музыки: ` +
        '<code>/гем сочини песню про дедлайны</code>',
      { parse_mode: 'HTML' },
    );
    return;
  }

  await ctx.editMessageText(await trackConfirmText(ctx, draft, true), {
    parse_mode: 'HTML',
  });

  try {
    const track = await withChatAction(ctx, 'upload_document', () =>
      generateTrack({
        stylePrompt: draft.stylePrompt,
        ...(draft.negativeStylePrompt ? { negativeStylePrompt: draft.negativeStylePrompt } : {}),
        lyrics: draft.lyrics,
        duration: draft.duration,
      }),
    );

    const left = Number.isFinite(quota.remaining) ? `, осталось на сегодня ${quota.remaining} из ${quota.limit}` : '';
    const extension = track.mimeType === 'audio/wav' ? 'wav' : 'mp3';

    await ctx.replyWithAudio(new InputFile(track.data, `track.${extension}`), {
      title: draft.title,
      performer: 'Ace-Step',
      duration: track.duration,
      caption:
        `🎵 <b>${escapeHtml(draft.title)}</b>\n` +
        `<i>${draft.duration} с, $${track.costUsd.toFixed(3)}, готовилось ${(track.elapsedMs / 1000).toFixed(0)} с${left}</i>`,
      parse_mode: 'HTML',
    });

    // Слова остаются в разделе — под ними и подпевают, — «пишу…» убираем.
    clearTrackDraft(ctx);
    await ctx
      .editMessageText(await trackConfirmText(ctx, draft, false), { parse_mode: 'HTML' })
      .catch(() => undefined);
  } catch (error) {
    // Трек не вышел — слот нормы возвращаем: платим за музыку, а не за попытку.
    // GoAPI берёт деньги за завершённую задачу, так что отказ на заказе или
    // в очереди не стоит ничего. Черновик оставляем и возвращаем кнопки —
    // можно попробовать ещё раз без нового плана.
    await trackQuota.release(userId);
    await ctx
      .editMessageText(await trackConfirmText(ctx, draft, false), {
        parse_mode: 'HTML',
        reply_markup: trackConfirmKeyboard(),
      })
      .catch(() => undefined);
    await replyWithError(ctx, error);
  }
}

/**
 * Решает, обращались ли фотографией к боту, и достаёт из подписи вопрос.
 *
 * В группе у бота отключён privacy mode (иначе не работает /гем), то есть он
 * видит вообще все картинки в чате. Отвечать на каждую нельзя — бот вклинивался
 * бы в любую беседу. Поэтому в группе нужен явный признак обращения: команда
 * в подписи либо ответ на сообщение самого бота. В личке признак не нужен.
 */
function resolveImageRequest(
  ctx: BotContext,
  caption: string,
  /**
   * Чем заменить пустую подпись. У снимка это «что на картинке?», у голосового
   * — ничего: там пустой запрос осмыслен сам по себе и означает «ответь по
   * сказанному» (см. VOICE_DEFAULT_TASK).
   */
  fallback: string = DEFAULT_IMAGE_PROMPT,
): { prompt: string } | null {
  const match = MEDIA_COMMAND.exec(caption.trim());

  // «/гем@другой_бот» в общем чате — не наше дело.
  const addressee = match?.[1];
  if (addressee && addressee.toLowerCase() !== ctx.me.username.toLowerCase()) return null;

  const repliesToBot = ctx.message?.reply_to_message?.from?.id === ctx.me.id;
  const isPrivate = ctx.chat?.type === 'private';

  if (!isPrivate && !match && !repliesToBot) return null;

  // С командой берём остаток подписи, без команды — всю подпись целиком.
  const asked = (match ? (match[2] ?? '') : caption).trim();
  return { prompt: asked || fallback };
}

/**
 * Команда реплаем на чужую (или свою) фотографию: «/гем что тут написано».
 *
 * Отдельная ветка нужна из-за того, как устроен Telegram: в таком сообщении
 * самой картинки нет, есть только ссылка на неё в reply_to_message. Обработчик
 * снимков ждёт фото в текущем сообщении и потому не срабатывал вовсе, а запрос
 * уходил в модель голым текстом — она честно отвечала словами про несуществующий
 * снимок. Поэтому картинку выкачиваем отсюда сами.
 */
async function handleRepliedPhoto(ctx: BotContext, fileId: string, rawPrompt: string): Promise<void> {
  const gemini = findTextProvider(GEMINI_ID);
  if (!gemini?.isConfigured) {
    await ctx.reply('🔌 Gemini не подключён — разбирать картинки некому.');
    return;
  }

  try {
    const image = await withChatAction(ctx, 'typing', () => downloadAttachment(ctx, fileId));

    const prompt = rawPrompt.trim() || DEFAULT_IMAGE_PROMPT;
    await askChain(ctx, gemini, resolveChain(SMART_CHAIN), prompt, { attachments: [image] });
  } catch (error) {
    await replyWithError(ctx, error);
  }
}

/** Реплай на сообщение с текстом или подписью — то, что можно процитировать. */
type QuotableMessage = { text?: string; caption?: string; from?: { id: number } };

/**
 * Вплетает цитату реплая в вопрос, если реплай на что-то есть.
 *
 * Общий приём для двух мест: явного «/гем реплаем + вопрос» и обычного
 * ответа реплаем на реплику бота (см. handleReplyToBot). Текст берём и
 * из text, и из caption — реплай может быть на фото или голосовое с
 * подписью, а не только на чистый текст.
 *
 * Сравнение с prompt отсекает случай, когда extractPrompt уже взял реплай
 * целиком за неимением своих слов, — цитировать текст сам на себя незачем.
 */
function buildReplyQuotePrompt(
  ctx: BotContext,
  prompt: string,
  repliedMessage: QuotableMessage | undefined,
  ownReplyLabel: 'вопрос' | 'ответ' = 'вопрос',
): string {
  const repliedText = (repliedMessage?.text ?? repliedMessage?.caption ?? '').trim();
  if (!repliedText || repliedText === prompt) return prompt;

  return repliedMessage?.from?.id === ctx.me.id
    ? `Пользователь отвечает на твою реплику:\n«${repliedText.slice(0, 700)}»\n\nЕго ${ownReplyLabel}: ${prompt}`
    : `Вопрос задан реплаем на сообщение в чате:\n«${repliedText.slice(0, 700)}»\n\nВопрос: ${prompt}`;
}

/**
 * Ответ реплаем на сообщение бота — продолжение разговора, а не новый запрос.
 *
 * Раньше на такую реплику бот в группе молчал, а в личке предлагал
 * «использовать команду»: формально верно, по-человечески глупо. Если человек
 * отвечает именно на реплику бота, обращение очевидно и без команды.
 *
 * Цитату подмешиваем в запрос, но не в историю. Во-первых, отвечать могут
 * на давнее сообщение, которое из истории уже вытеснено. Во-вторых, в живом
 * топике у бота десяток реплик подряд, и без цитаты непонятно, какую именно
 * имеют в виду.
 */
async function handleReplyToBot(ctx: BotContext, text: string, repliedMessage: QuotableMessage): Promise<void> {
  const gemini = await requireGemini(ctx);
  if (!gemini) return;

  const prompt = buildReplyQuotePrompt(ctx, text, repliedMessage, 'ответ');

  await askChain(ctx, gemini, resolveChain(SMART_CHAIN), prompt, { historyText: text });
}

/**
 * Присланный файл: книга, статья, выгрузка.
 *
 * Всегда уходит цепочкой флешей, какой бы режим ни стоял в разделе: у Gemma
 * окно 262 тысячи токенов против миллиона у них, а PDF она не принимает вовсе.
 *
 * Текст файла попадает в запрос, но не в историю — иначе одна книга занимала бы
 * контекст следующие триста сообщений. В историю уходит только строчка о том,
 * что файл был, и ответ модели: этого хватает, чтобы дальше спрашивать «а что
 * там про X» без повторной пересылки файла.
 */
async function handleDocument(ctx: BotContext, fileId: string, fileName: string, caption: string): Promise<void> {
  const request = resolveImageRequest(ctx, caption);
  if (!request) return;

  const gemini = await requireGemini(ctx);
  if (!gemini) return;

  const notice = await ctx.reply(`📄 Читаю «${fileName}»…`);

  try {
    const file = await withChatAction(ctx, 'typing', () => downloadAttachment(ctx, fileId));
    const prepared = await prepareDocument(file.data, fileName);

    // Вопрос человека или, если его нет, просьба пересказать: присылать книгу
    // молча — это обычно «прочитай и расскажи».
    const question = request.prompt === DEFAULT_IMAGE_PROMPT ? 'Перескажи, о чём этот файл, и выдели главное.' : request.prompt;

    const prompt = prepared.text
      ? `Файл «${fileName}»:\n\n${prepared.text}\n\n---\n\n${question}`
      : question;

    await ctx.api
      .editMessageText(
        notice.chat.id,
        notice.message_id,
        `📄 «${fileName}» — ${prepared.tokens.toLocaleString('ru')} токенов${prepared.note ? `, ${prepared.note}` : ''}. Думаю…`,
      )
      .catch(() => undefined);

    await askChain(ctx, gemini, resolveChain(THINK_CHAIN), prompt, {
      attachments: prepared.attachment ? [prepared.attachment] : [],
      historyText: `Прислал файл «${fileName}» (${prepared.tokens.toLocaleString('ru')} токенов). ${question}`,
    });

    await ctx.api.deleteMessage(notice.chat.id, notice.message_id).catch(() => undefined);
  } catch (error) {
    await ctx.api.deleteMessage(notice.chat.id, notice.message_id).catch(() => undefined);
    await replyWithError(ctx, error);
  }
}

/** То немногое, что нужно от голосового: где взять файл и сколько он длится. */
interface VoiceMessage {
  file_id: string;
  duration: number;
  mime_type?: string;
}

/** Длительность записи человеческим видом: 0:42, 3:05. */
function formatDuration(seconds: number): string {
  return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`;
}

/**
 * Голосовое сообщение: бот слушает запись и отвечает по сказанному.
 *
 * Отдельного «распознавания речи» здесь нет и не нужно. Голосовое уходит в
 * модель ровно тем же путём, что фотография, — вложением в обычный запрос
 * (см. inlineData в src/services/gemini.ts). Google берёт за звук 32 токена
 * на секунду, так что минута разговора обходится примерно в 2000 токенов:
 * дешевле, чем пара снимков, и несравнимо щедрее озвучки, у которой своя
 * отдельная норма в десяток запросов на модель в сутки.
 *
 * Цепочка своя, голосовая: в основной резервом стоит Gemma, а она звука не
 * слышит, и отказ этот неперебираемый (см. config.gemini.chains.voice). А сама запись перед отправкой
 * проходит через prepareVoice — это про формат, см. src/services/voice.ts.
 *
 * В историю раздела попадают маркер голосового с конспектом сказанного
 * (~1000 знаков из ответа модели) и ответ бота. Само аудио там не сохраняется —
 * как и содержимое снимков. На продолжение разговора этого хватает: о чём шла
 * речь, видно из конспекта и ответа.
 */
async function handleVoice(ctx: BotContext, voice: VoiceMessage, question: string): Promise<void> {
  // Дословная выписка — единственный ответ по голосовому, который обязан быть
  // длинным: пять минут речи это тысячи знаков, и «покороче» здесь означало бы
  // «перескажи», то есть ровно не то, о чём попросили.
  const verbatim = question === VOICE_VERBATIM_TASK;

  const gemini = await requireGemini(ctx);
  if (!gemini) return;

  const length = formatDuration(voice.duration ?? 0);

  try {
    // mime_type у голосовых Telegram присылает сам — обычно audio/ogg.
    // prepareVoice приводит запись к формату, который Google принимает
    // наверняка: OGG у Telegram всегда с кодеком Opus, а Google документирует
    // Vorbis (см. src/services/voice.ts).
    const audio = await withChatAction(ctx, 'typing', async () =>
      prepareVoice(await downloadAttachment(ctx, voice.file_id, voice.mime_type ?? 'audio/ogg')),
    );

    logger.info('Разбираю голосовое', {
      length,
      kb: Math.round(audio.data.length / 1024),
      mime: audio.mimeType,
      asked: question || '(без вопроса)',
    });

    const marker = `Прислал голосовое (${length}).${verbatim ? ' Расшифровка.' : question ? ` ${question}` : ''}`;
    const ok = await askChain(ctx, gemini, resolveChain(VOICE_CHAIN), `${VOICE_RULE}\n\n${question || VOICE_DEFAULT_TASK}`, {
      attachments: [audio],
      historyText: marker,
      ...(verbatim ? { answerLength: 'unbounded' as const } : {}),
    });

    // В историю — маркер + конспект сказанного (~1000 знаков), а не голый
    // маркер: иначе дальше по разговору модель видит вопрос по голосовому,
    // но не то, о чём в нём говорилось. Отдельного STT-прохода нет, поэтому
    // конспект берём из ответа модели: при «!расшифруй» это дословная выписка,
    // при ответе по существу — суть сказанного. Запись правим на месте, новых
    // сообщений в историю не добавляем — бюджет живого хвоста те же 15.
    if (ok && config.ai.historyMaxTokens > 0) {
      const history = ctx.session.history;
      const prev = history[history.length - 2];
      const last = history[history.length - 1];
      if (prev?.role === 'user' && last?.role === 'assistant' && prev.text.includes(marker)) {
        const summary = last.text.replace(/\s+/g, ' ').trim().slice(0, 1000);
        if (summary) prev.text += `\nКонспект: ${summary}`;
      }
    }
  } catch (error) {
    await replyWithError(ctx, error);
  }
}

/** Скачивает картинки и отправляет их в модель вместе с вопросом. */
async function handlePhotos(ctx: BotContext, fileIds: string[], caption: string): Promise<void> {
  const request = resolveImageRequest(ctx, caption);
  if (!request) return;

  const gemini = findTextProvider(GEMINI_ID);
  if (!gemini?.isConfigured) {
    await ctx.reply('🔌 Gemini не подключён — разбирать картинки некому.');
    return;
  }

  try {
    const attachments = await withChatAction(ctx, 'typing', () =>
      Promise.all(fileIds.map((fileId) => downloadAttachment(ctx, fileId))),
    );

    await askChain(ctx, gemini, resolveChain(SMART_CHAIN), request.prompt, { attachments });
  } catch (error) {
    await replyWithError(ctx, error);
  }
}

// ВНИМАНИЕ-ловушка: registerAiCommands ставит терминальный bot.on('message:text') (без next()). Любой bot.command/hears/on('message:text'), зарегистрированный ПОСЛЕ него, недостижим — grammy идёт по middleware по порядку. Новые команды — только ДО registerAiCommands либо с next().
export function registerAiCommands(bot: Bot<BotContext>): void {
  // Кнопки заказа трека: черновик в сессии + TTL, деньги только по «Заказать»
  // (см. handleTrack/orderTrack выше). Чужая кнопка чужой черновик не трогает:
  // черновик ищется по id нажавшего, чужому отвечает «протух».
  bot.callbackQuery(`${TRACK_CB}:go`, async (ctx) => {
    const draft = getTrackDraft(ctx);
    if (!draft) {
      await ctx.answerCallbackQuery({ text: 'Этот заказ уже не действует — попросите заново.', show_alert: true });
      return;
    }

    await ctx.answerCallbackQuery();
    await ctx.editMessageReplyMarkup({ reply_markup: undefined }).catch(() => undefined);
    await orderTrack(ctx, draft);
  });

  bot.callbackQuery(`${TRACK_CB}:cancel`, async (ctx) => {
    // Слот нормы при отмене возвращать нечего — он ещё не занимался, так задумано.
    clearTrackDraft(ctx);
    await ctx.answerCallbackQuery({ text: 'Отменено' });
    await ctx.editMessageText('✖️ Заказ отменён. Ничего не потрачено.');
  });

  // ------------------------------------------------------- /gem и /гем
  bot.command('gem', async (ctx, next) => {
    // Команда в подписи к фотографии — не наше дело: снимок разбирает
    // обработчик ниже, он умеет и склейку альбомов. Пропускаем
    // ход, иначе подпись с вопросом отвечала бы текстом без картинки.
    if (ctx.message?.photo) return next();

    // То же и с подписью к голосовому. Написать её позволяет не всякий клиент,
    // но если написали — запись должен разобрать обработчик голосовых, иначе
    // бот ответит на подпись текстом, будто никакого голосового и не было.
    if (ctx.message?.voice) return next();

    await handleGemini(ctx, extractPrompt(ctx, ctx.match));
  });

  bot.hears(CYRILLIC_GEM, async (ctx, next) => {
    // ctx.match для регулярки — результат exec; для строкового триггера это string.
    const match = typeof ctx.match === 'string' ? null : ctx.match;
    const addressee = match?.[1];

    // В группе может быть несколько ботов: /гем@другой_бот — не наше дело.
    if (addressee && addressee.toLowerCase() !== ctx.me.username.toLowerCase()) return;

    // hears в grammY срабатывает и на подпись к фотографии — отдаём её
    // обработчику снимков по той же причине, что и латинскую форму команды.
    if (ctx.message?.photo) return next();
    if (ctx.message?.voice) return next();

    await handleGemini(ctx, extractPrompt(ctx, match?.[2] ?? ''));
  });

  // ------------------------------------------------------------ картинки
  // Альбом Telegram присылает несколькими апдейтами с общим media_group_id:
  // копим их и отправляем в модель одним запросом, иначе на альбом из пяти
  // снимков прилетело бы пять отдельных ответов.
  bot.on('message:photo', async (ctx) => {
    const fileId = pickPhotoFileId(ctx.message.photo);
    if (!fileId) return;

    const caption = ctx.message.caption ?? '';
    const albumId = ctx.message.media_group_id;

    if (albumId) {
      collectAlbumPart(ctx, albumId, fileId, caption, handlePhotos);
      return;
    }

    await handlePhotos(ctx, [fileId], caption);
  });

  // ------------------------------------------------------------- файлы
  // Книги, статьи, выгрузки. Правила обращения те же, что у картинок:
  // в личке достаточно файла, в группе нужна подпись с командой.
  bot.on('message:document', async (ctx) => {
    const document = ctx.message.document;
    await handleDocument(ctx, document.file_id, document.file_name ?? 'файл', ctx.message.caption ?? '');
  });

  // ---------------------------------------------------------- голосовые
  // Правила обращения общие для всех вложений (см. resolveImageRequest):
  // в личке достаточно самого голосового, в группе — либо подпись с командой
  // (её позволяют не все клиенты), либо голосовое реплаем на реплику бота.
  // Показать боту чужое голосовое в группе можно только реплаем с «/гем» —
  // эту ветку разбирает handleGemini.
  bot.on('message:voice', async (ctx) => {
    const request = resolveImageRequest(ctx, ctx.message.caption ?? '', '');
    if (!request) return;

    await handleVoice(ctx, ctx.message.voice, request.prompt);
  });

  // --------------------------------------------------- обычные сообщения
  // Регистрируется последним: сюда попадает всё, что не разобрали
  // предыдущие обработчики.
  bot.on('message:text', async (ctx) => {
    const text = ctx.message.text.trim();
    const replyTo = ctx.message.reply_to_message;

    // Ответ реплаем на реплику бота — продолжение разговора. Команда здесь
    // не нужна: обращение и так очевидно, причём и в группе тоже. Это
    // единственный случай, когда бот отвечает в группе на обычный текст.
    if (replyTo?.from?.id === ctx.me.id && text && !text.startsWith('/')) {
      await handleReplyToBot(ctx, text, replyTo);
      return;
    }

    // В остальном в группах бот молчит на обычные сообщения: обращаться
    // к нему нужно командой. Иначе он вклинивался бы в каждую беседу.
    if (ctx.chat.type !== 'private') return;

    if (text.startsWith('/')) {
      await ctx.reply('🤔 Не знаю такую команду. Список всех команд — /help');
      return;
    }

    // Свободный текст запросом не считается — это осознанное решение,
    // чтобы случайные сообщения не тратили квоту нейросети.
    await ctx.reply('Чтобы спросить нейросеть, используйте команду. Например:\n/гем ' + text.slice(0, 100));
  });
}
