/**
 * Цепочки моделей и их назначение.
 *
 * Идея простая: бот не выбирает модель под каждое сообщение, а работает
 * цепочками. Первая модель в цепочке отвечает, остальные подхватывают, если
 * она отказала. Так лимиты перестают быть проблемой без всякого учёта квот:
 * дневная норма первой модели кончилась — запрос молча уходит следующей.
 *
 * Содержательных цепочки две, потому что и задач по сути две: обычный
 * разговор и «подумать как следует». Выбирает их не человек, а сама команда:
 * /гем идёт основной, «!контекст» и «!сеть» — сильной (поиск разбирает
 * найденные страницы той же головой, что и «подумать» — короткая выжимка
 * без рассуждения там ничем не лучше). Выбор цепочки на раздел командой
 * /режим когда-то был и убран: на небольшую группу настраивать топики
 * оказалось некому, а лишний пункт в справке путал. Состав цепочек правится
 * в .env.
 *
 * Третья, голосовая, стоит особняком и задачей не является: это та же
 * основная, из которой вычеркнуты модели, не умеющие слушать (см. ниже).
 *
 * Общее у двух из трёх — голова: и в основной, и в голосовой первым стоит
 * flash-lite. Исключение — сильная цепочка: она заведена ради качества
 * рассуждения, и скорость там уступает. Дальше порядок расходится. В
 * разговоре ниже флешей стоит Gemma — она медленная, но дневная норма
 * у неё огромная, и она же последняя страховка цепочки. Прошлое поколение
 * (gemini-2.5-flash, gemini-2.5-flash-lite), которое раньше стояло под ней,
 * убрано из всех цепочек 21.08.2026 — Google отдаёт по ним 404 «no longer
 * available to new users», и перебор впустую упирался в мёртвые звенья.
 * В «подумать» Gemma в самом хвосте: этой цепочкой идут и PDF, и поиск,
 * а Gemma либо отбивает их неперебираемой ошибкой (PDF), либо не
 * укладывается в таймаут (поиск — проверено на живом боте).
 * В голосовую она не попадает вовсе, и не по порядку, а по неумению:
 * звука Gemma не слышит.
 *
 * Сами имена моделей лежат в конфигурации и правятся через .env —
 * см. комментарий у config.gemini.chains.
 */
import { config } from './config.js';

/** Идентификаторы цепочек. Хранятся в сессии топика, поэтому это строки. */
export const MAIN_CHAIN = 'main';
export const THINK_CHAIN = 'think';
export const VOICE_CHAIN = 'voice';

export interface ChainInfo {
  id: string;
  /** Короткое имя для кнопки. */
  title: string;
  /** Для чего эта цепочка. Показывается в /status и в логах. */
  hint: string;
  /** Модели по порядку: первая основная, дальше резерв. */
  models: string[];
  /**
   * Потолок ответа в токенах. У каждой цепочки свой: он упирается не в силу
   * модели, а в её минутную норму (см. config.gemini.maxOutput).
   */
  maxOutputTokens: number;
}

/** Все цепочки. Первая считается основной. */
export function listChains(): ChainInfo[] {
  return [
    {
      id: MAIN_CHAIN,
      title: 'Обычный',
      hint: 'Разговор, вопросы, картинки, документы. Запас практически бесконечный.',
      models: config.gemini.chains.main,
      maxOutputTokens: config.gemini.maxOutput.main,
    },
    {
      id: THINK_CHAIN,
      title: 'Подумать',
      hint: 'Сложные задачи и код. Дневная норма небольшая — примерно 10 запросов на человека.',
      models: config.gemini.chains.think,
      maxOutputTokens: config.gemini.maxOutput.think,
    },
    {
      id: VOICE_CHAIN,
      title: 'Голос',
      hint: 'Голосовые сообщения. Всё то же, что в обычной, только без моделей, которые не слышат.',
      models: config.gemini.chains.voice,
      // Ответ на голосовое идёт в чат обычным сообщением — значит и потолок
      // тот же, что у обычного разговора.
      maxOutputTokens: config.gemini.maxOutput.main,
    },
  ];
}

/**
 * Возвращает цепочку по идентификатору. Незнакомый идентификатор —
 * не повод падать: имя цепочки могло приехать из старой сессии или из
 * опечатки в коде, поэтому молча откатываемся на основную.
 */
export function resolveChain(id: string | undefined): ChainInfo {
  const chains = listChains();
  return chains.find((chain) => chain.id === id) ?? chains[0]!;
}
