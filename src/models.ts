/**
 * Цепочки моделей и их назначение.
 *
 * Идея простая: бот не выбирает модель под каждое сообщение, а работает
 * цепочками. Первая модель в цепочке отвечает, остальные подхватывают, если
 * она отказала. Так лимиты перестают быть проблемой без всякого учёта квот:
 * дневная норма первой модели кончилась — запрос молча уходит следующей.
 *
 * Содержательная цепочка одна — умная: обычный разговор, «!сеть»,
 * «!файл» и присланные документы идут ею же. Отдельной сильной
 * цепочки «Подумать» больше нет: владелец признал её полным дублем умной,
 * и THINK_CHAIN остался лишь алиасом smart для старых сессий (см. ниже).
 * Поиск разбирает найденные страницы той же умной головой — короткая
 * выжимка без рассуждения там ничем не лучше. Выбор цепочки на раздел
 * командой /режим когда-то был и убран: на небольшую группу настраивать
 * топики оказалось некому, а лишний пункт в справке путал. Состав цепочек
 * правится в .env.
 *
 * Вторая, быстрая, — для формальных JSON-планов (рисование, !скажи, !трек).
 * Третья, голосовая, стоит особняком и задачей не является: это та же
 * умная, из которой вычеркнуты модели, не умеющие слушать (см. ниже).
 *
 * Общее у двух из трёх — lite-хвост: и в умной, и в голосовой, и в быстрой
 * запас один и тот же (flash-lite 3.5 → flash-lite 3.1 → Gemma). Gemma
 * медленная (25 секунд против полутора у flash-lite — замерено на живом
 * боте), но дневная норма у неё огромная, и она же последняя страховка
 * цепочки. Прошлое поколение (gemini-2.5-flash, gemini-2.5-flash-lite),
 * которое раньше стояло под ней, убрано из всех цепочек 21.08.2026 —
 * Google отдаёт по ним 404 «no longer available to new users», и перебор
 * впустую упирался в мёртвые звенья.
 * В голосовую Gemma не попадает вовсе, и не по порядку, а по неумению:
 * звука Gemma не слышит.
 *
 * Первые уровни обеих двухуровневых цепочек живут на OpenRouter (см.
 * config.openai.chains и resolveSmartLevels/resolveFastLevels в registry.ts):
 * smart — contrib → full → luna, fast — середина luna → contrib (точный плоский
 * порядок владельца: lite-голова → luna → contrib → Gemma-хвост). За ними —
 * Gemini-хвосты из config.gemini.chains.
 *
 * Сами имена моделей лежат в конфигурации и правятся через .env —
 * см. комментарий у config.gemini.chains.
 */
import { config } from './config.js';

/** Идентификаторы цепочек. Хранятся в сессии топика, поэтому это строки. */
export const MAIN_CHAIN = 'main';
/**
 * Алиас умной цепочки (удалена как отдельная: полный дубль smart).
 * Экспорт и значение оставлены: лежат в старых сессиях топиков.
 * resolveChain() маппит его на smart (см. ниже).
 */
export const THINK_CHAIN = 'think';
export const VOICE_CHAIN = 'voice';
/**
 * Умная и быстрая цепочки (п.3 плана: OpenRouter pay-as-you-go + Gemini-хвост).
 *
 * smart — всё содержательное: разговор, картинки, документы,
 * «!сеть», «!файл». Первый уровень `OPENAI_CHAIN_SMART` (contrib→full→luna),
 * второй — Gemini main-хвост. Замер contrib-про-пустоту и пол 4000
 * в registry.ts сохранены: потолок smart не опускать ниже 4000.
 * fast — формальные JSON-планы (рисование, !скажи, !трек): три уровня
 * (L1 Gemini lite-голова → L2 OpenRouter luna→contrib → L3 Gemma-хвост,
 * см. resolveFastLevels), второй — отдельный Gemini fast-хвост
 * (GEMINI_CHAIN_FAST, не LIGHT).
 *
 * voice остаётся чисто на Gemini: звук через OpenRouter не проверен
 * (тест п.1.5 покрыл только картинки), а неперебираемый отказ на голосовом
 * показал бы человеку ошибку вместо ответа.
 */
export const SMART_CHAIN = 'smart';
export const FAST_CHAIN = 'fast';

export interface ChainInfo {
  id: string;
  /** Короткое имя для кнопки. */
  title: string;
  /** Для чего эта цепочка. Показывается в /status и в логах. */
  hint: string;
  /** Модели по порядку: первая основная, дальше резерв. */
  models: string[];
  /**
   * Потолок ответа в токенах. У каждой цепочки свой: он упирается не в силу
   * модели, а в её минутную норму (см. config.gemini.maxOutput).
   */
  maxOutputTokens: number;
}

/** Все цепочки. Первая считается основной. Отдельной think нет — см. THINK_CHAIN выше. */
export function listChains(): ChainInfo[] {
  return [
    {
      id: SMART_CHAIN,
      title: 'Умный',
      hint: 'Разговор, вопросы, картинки, документы, !сеть. Голова — OpenRouter, запас — Gemini.',
      // Второй уровень (Gemini-хвост); первый (OpenRouter) берётся из
      // config.openai.chains.smart в generateWithFallback (см. registry.ts).
      models: config.gemini.chains.main,
      maxOutputTokens: config.gemini.maxOutput.main,
    },
    {
      id: FAST_CHAIN,
      title: 'Быстрый',
      hint: 'Служебные планы (рисование, озвучка, треки). Уровни: lite-голова, OpenRouter (luna→contrib), Gemma-хвост.',
      models: config.gemini.chains.fast,
      maxOutputTokens: config.gemini.maxOutput.main,
    },
    {
      id: VOICE_CHAIN,
      title: 'Голос',
      hint: 'Голосовые сообщения. Всё то же, что в обычной, только без моделей, которые не слышат.',
      models: config.gemini.chains.voice,
      // Ответ на голосовое идёт в чат обычным сообщением — значит и потолок
      // тот же, что у обычного разговора.
      maxOutputTokens: config.gemini.maxOutput.main,
    },
  ];
}

/**
 * Возвращает цепочку по идентификатору. Незнакомый идентификатор —
 * не повод падать: имя цепочки могло приехать из старой сессии или из
 * опечатки в коде, поэтому молча откатываемся на основную.
 *
 * Отдельно: THINK_CHAIN — удалённая цепочка «Подумать», её id лежат
 * в старых сессиях. Маппим на smart явно (а не на chains[0] по умолчанию),
 * чтобы алиас не зависел от порядка в listChains().
 */
export function resolveChain(id: string | undefined): ChainInfo {
  const chains = listChains();
  if (id === THINK_CHAIN) return chains.find((chain) => chain.id === SMART_CHAIN) ?? chains[0]!;
  return chains.find((chain) => chain.id === id) ?? chains[0]!;
}
