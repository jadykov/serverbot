/**
 * Сборка запроса к Ace-Step: стиль музыки и слова песни.
 *
 * Зачем этот шаг. Модель ждёт не «сделай песню про дедлайны», а две разные
 * вещи: style_prompt — теги про музыку по-английски, и lyrics — собственно
 * слова песни. Написать это руками каждый раз никто не станет, а без слов
 * Ace-Step отдаёт инструментал.
 * Поэтому черновик собирает бесплатный Gemini на лёгкой формальной цепочке
 * (GEMINI_CHAIN_LIGHT — той же, что и у свободного разбора «!скажи», см.
 * planSpeech в services/gemini-tts.ts): задача формальная, и тяжёлая модель
 * тратит на неё двадцать секунд, ничего не выигрывая. Рисование этой цепочкой
 * больше не пользуется — оно с 21.08.2026 на THINK_CHAIN (см. commands/draw.ts).
 *
 * Что известно про эту модель (карточка ace-step/ACE-Step и её примеры):
 *
 *  • style_prompt читается как набор тегов через запятую, а не как рассказ:
 *    жанр, настроение, инструменты, тип голоса, темп. Длинное описание
 *    сценой она размывает;
 *  • по документации структура песни задаётся тегами в самих словах —
 *    [verse], [chorus], [bridge], — но здесь ими сознательно не пользуемся:
 *    на живых треках 21.08.2026 модель на русском тексте пела такой тег
 *    как есть, будто это часть слов, а не служебная разметка (тренирована
 *    она в основном на английских текстах). «[inst]» вместо слов
 *    по-прежнему означает инструментал без вокала — это отдельный режим,
 *    а не тег структуры, его не убираем;
 *  • язык слов модель определяет по самим словам, отдельного поля нет —
 *    поэтому русский текст так и пишется по-русски;
 *  • длительность — параметр запроса, а не просьба в промпте, и она же
 *    цена: платится секунда готового звука;
 *  • длина вступления и концовки отдельным полем не задаётся, зато есть
 *    negative_style_prompt — то, чего в звуке быть не должно. Вместе
 *    с тегами в style_prompt и словами в lyrics это уже три независимых
 *    рычага против долгого проигрыша, а не один (см. INTRO_SECONDS,
 *    OUTRO_SECONDS и NEGATIVE_STYLE_PROMPT ниже).
 */
import { config } from '../config.js';
import { logger } from '../logger.js';
import { generateWithChain } from './chain.js';
import type { TextProvider } from '../types.js';

/** Что именно закажем у Ace-Step. */
export interface SongPlan {
  /** Теги про музыку, по-английски. */
  stylePrompt: string;
  /**
   * Чего в музыке быть не должно, по-английски — фиксированный набор,
   * не зависит от замысла (см. NEGATIVE_STYLE_PROMPT). Отдельным полем
   * от модели не просим: это продуктовое решение «короткие края всегда»,
   * а не то, что стоит доверять творчеству помощника заново на каждой песне.
   */
  negativeStylePrompt: string;
  /** Слова с разметкой структуры или «[inst]» для инструментала. */
  lyrics: string;
  /** Название трека по-русски — для подписи и имени файла. */
  title: string;
  /** Длительность в секундах: названная человеком или из настроек. */
  duration: number;
}

/** Инструментал — то же самое слово, которым его обозначает сама модель. */
const INSTRUMENTAL = '[inst]';

/**
 * Вступление — считай что его нет: пение начинается с первой-второй секунды,
 * не позже. Раньше здесь стояли те же 5 секунд, что и у концовки, но именно
 * ожидание вступления и было главной причиной, почему треки казались обрубленными
 * — секунды, потраченные на проигрыш, потом неоткуда взять для слов.
 */
const INTRO_SECONDS = 1;

/**
 * Концовка может быть чуть длиннее вступления — модели нужно место, чтобы
 * не обрубить последнее слово на полуслове, но и она короткая: долгое
 * затухание на короткий трек не помещается.
 */
const OUTRO_SECONDS = 3;

/**
 * Сколько строк просить у помощника — фиксированно, не по формуле от
 * длительности.
 *
 * Раньше строки считались как «(длительность − края) / 4» и на сорока
 * секундах получалось 7-8 — вроде разумно, но модель словам тесно не бывает:
 * она то поёт быстрее расчёта, то раздувает строку повторами, и трек обрывался
 * на середине фразы чаще, чем оставался с запасом. Фиксированные 5-8 строк
 * не зависят ни от длительности, ни от арифметики — они всегда умещаются
 * с большим запасом, а лишнее время трек занимает проигрышем и повтором
 * куплета/припева, что для короткой песни и так нормальное устройство.
 */
const LYRICS_LINES = '5-8';

/**
 * Второй, более сильный рычаг против долгого проигрыша — negative_style_prompt
 * у Ace-Step, который тегам в style_prompt не всегда подчиняется (это же
 * творческая модель, а не строгий парсер). Фиксированный список, не зависит
 * от замысла песни: короткие края нужны всегда, а не только когда попросили.
 */
const NEGATIVE_STYLE_PROMPT =
  'long intro, slow build-up, instrumental intro, spoken word intro, late vocal entry, ' +
  'long outro, extended fade-out, noise';

/** Достаёт JSON из ответа модели: она любит завернуть его в ```json … ```. */
function parseJsonAnswer(text: string): unknown {
  const withoutFence = text.replace(/```(?:json)?/gi, ' ').trim();

  const start = withoutFence.indexOf('{');
  const end = withoutFence.lastIndexOf('}');
  if (start === -1 || end === -1) throw new Error('в ответе нет JSON-объекта');

  const candidate = withoutFence.slice(start, end + 1);

  try {
    return JSON.parse(candidate);
  } catch {
    // Те же две болячки, что и у помощника по картинкам: лишняя запятая
    // перед закрывающей скобкой и «умные» кавычки вместо обычных.
    return JSON.parse(candidate.replace(/,(\s*[}\]])/g, '$1').replace(/[«»„“”]/g, '"'));
  }
}

/**
 * Собирает инструкцию.
 *
 * Число строк — фиксированное (LYRICS_LINES), не привязанное к длительности:
 * так надёжнее, чем формула «секунды минус края, делить на четыре» — та
 * выглядела точной, а на практике модель то пела быстрее расчёта, то
 * растягивала строку повторами, и трек обрывался на середине фразы.
 * Разница между короткой и длинной песней теперь не в числе строк,
 * а в том, сколько раз Ace-Step их повторит и сколько добавит проигрыша —
 * это его работа, не наша.
 */
function instruction(): string {
  const { duration, minDuration, maxDuration } = config.goapi.music;

  return [
    'Ты готовишь запрос к модели генерации музыки Ace-Step по замыслу пользователя.',
    '',
    'Модели нужны две разные вещи, и путать их нельзя:',
    '• style_prompt — музыка, набором тегов через запятую и ТОЛЬКО по-английски:',
    '  жанр, настроение, инструменты, тип голоса (female vocal, male vocal, choir),',
    '  темп. От 5 до 12 тегов, без предложений и без пересказа сюжета песни.',
    '  Последними обязательно добавь теги про края: instant vocal entry, no intro, short outro',
    '  (для инструментала — short intro, short outro: вокала там нет).',
    '• lyrics — сами слова песни, без тегов структуры вроде [verse]/[chorus]/[bridge]:',
    '  на русском тексте модель нередко поёт такой тег как есть, будто это часть слов.',
    '  Просто строки текста, разделяй пустой строкой там, где просится смена куплет/припев.',
    '  Язык слов — язык замысла пользователя: русский замысел — русские слова.',
    '  Пиши настоящий текст, а не описание того, о чём он будет.',
    '',
    'Трек короткий, и проигрыш в нём — выброшенные секунды. Поэтому:',
    `• вступления нет вовсе — пение начинается не позже ${INTRO_SECONDS}-й секунды. Первая же строка`,
    '  lyrics должна быть словами песни, без вступительных ремарок.',
    `• концовка не длиннее ${OUTRO_SECONDS} секунд после последних слов — песня заканчивается`,
    '  на словах, а не на затухании.',
    '',
    `Длительность: ${duration} секунд по умолчанию. Если человек назвал своё время`,
    `(«полминуты», «секунд десять»), верни его в секундах, от ${minDuration} до ${maxDuration}.`,
    `Больше ${maxDuration} не проси: столько всё равно не закажут.`,
    '',
    `Строк в lyrics — ровно ${LYRICS_LINES}, независимо от длительности: короче писать не нужно,`,
    'длиннее — тоже. Это не вся песня, а её ядро: сколько раз повторить куплет и припев',
    'и сколько добавить инструментальных тактов, решает сама Ace-Step по духу жанра.',
    'Строки — короткие, по 4-8 слов: длинную строку модель либо зачитает скороговоркой,',
    'либо оборвёт на середине.',
    '',
    `Если человек просит музыку без вокала (инструментал, минус, фон), верни lyrics ровно «${INSTRUMENTAL}».`,
    'Во всех остальных случаях песня со словами — это то, зачем команду и позвали.',
    '',
    'Если следом дали ещё и сообщение из чата («ситуацию») — это сюжет песни:',
    'слова пиши про него, не про замысел буквально. Замысел («грустная», «в стиле рэп»,',
    '«с издёвкой») — это тон и жанр, ситуация — то, о чём тон и жанр звучат.',
    'В лоб не цитируй, если не попросили дословно, — перескажи песней, своими словами.',
    '',
    'Ответь строго одним JSON-объектом без пояснений:',
    '{"style_prompt":"теги по-английски",',
    ' "lyrics":"строка\\nстрока\\n\\nстрока\\nстрока",',
    ' "title":"короткое название по-русски",',
    ' "duration":секунды}',
  ].join('\n');
}

/** Приводит ответ модели к нашему виду. null — разобрать не вышло. */
function toPlan(text: string): SongPlan | null {
  try {
    const parsed = parseJsonAnswer(text) as {
      style_prompt?: unknown;
      lyrics?: unknown;
      title?: unknown;
      duration?: unknown;
    };

    const stylePrompt = typeof parsed.style_prompt === 'string' ? parsed.style_prompt.trim() : '';
    const lyrics = typeof parsed.lyrics === 'string' ? parsed.lyrics.trim() : '';

    // Стиль — единственное обязательное поле запроса: без него заказывать нечего.
    if (!stylePrompt) return null;

    const duration = typeof parsed.duration === 'number' ? parsed.duration : Number(parsed.duration);

    return {
      stylePrompt,
      negativeStylePrompt: NEGATIVE_STYLE_PROMPT,
      lyrics: lyrics || INSTRUMENTAL,
      title: typeof parsed.title === 'string' && parsed.title.trim() ? parsed.title.trim() : '',
      duration: Number.isFinite(duration) && duration > 0 ? duration : config.goapi.music.duration,
    };
  } catch (error) {
    logger.debug('Ответ помощника по песне не разобрался как JSON', {
      error: error instanceof Error ? error.message : String(error),
    });
    return null;
  }
}

/**
 * Просит помощника собрать песню, давая ему второй шанс.
 *
 * null означает «не вышло»: в отличие от рисования, откатиться на исходный
 * запрос здесь нельзя. Русская фраза в style_prompt даст модели не тот
 * стиль, а слов не даст вовсе — вместо песни приедет инструментал за те же
 * деньги. Лучше честно не начинать: этот шаг бесплатный, а трек — нет.
 *
 * situation — реплай на сообщение («!трек песня о ситуации» ответом на чужую
 * реплику): текст, о котором должна быть песня. Отдельно от request, потому
 * что роли разные — request это тон и жанр («грустная», «в стиле рэп»),
 * а situation это сюжет, который в лоб просить неоткуда, если он уже написан
 * в чате до команды.
 */
export async function planSong(
  provider: TextProvider,
  models: string[],
  request: string,
  situation?: string,
): Promise<SongPlan | null> {
  const system = instruction();
  const userMessage = situation
    ? `Замысел пользователя: ${request}\n\n` +
      `Сообщение из чата, реплаем на которое попросили песню, — сама ситуация,\n` +
      `о которой должны быть слова:\n${situation}`
    : `Замысел пользователя: ${request}`;

  for (const attempt of [1, 2]) {
    const answer = await generateWithChain(provider, models, userMessage, {
      systemPrompt: attempt === 1 ? system : `${system}\n\nВАЖНО: ответ должен быть ровно одним JSON-объектом.`,
      temperature: 0.8,
    });

    const plan = toPlan(answer.text);
    if (plan) return plan;

    logger.warn('Помощник по песне вернул не JSON, пробую ещё раз', { attempt });
  }

  return null;
}

/** Инструментал ли это. Нужно и для подписи, и для лога. */
export function isInstrumental(plan: SongPlan): boolean {
  return plan.lyrics.trim().toLowerCase() === INSTRUMENTAL;
}
