/**
 * Подготовка голосового сообщения к отправке в модель.
 *
 * Задача одна и чисто форматная. Telegram отдаёт голосовые в OGG с кодеком
 * **Opus** — другого он не отдаёт вовсе. Google в списке принимаемых форматов
 * пишет «OGG **Vorbis**»: контейнер тот же, кодек другой. На практике Opus
 * обычно проезжает, но «обычно» — не то слово, на котором хочется строить
 * работающую команду, а отказ по формату неперебираемый: следующая модель
 * в цепочке ответит ровно то же самое.
 *
 * Поэтому, если в системе есть ffmpeg, запись перекодируется в FLAC —
 * формат, записанный в документации Google буквально.
 *
 * Почему именно FLAC, а не MP3: кодировщик FLAC в ffmpeg встроенный, а MP3
 * требует libmp3lame — внешнюю библиотеку, которой в чужой сборке может
 * не оказаться. Проверить это на машине, где ffmpeg вообще не стоит, нельзя,
 * а узнавать о таком из отказа на сервере — плохой способ. WAV встроен
 * так же, но весит вдвое больше при том же звуке.
 *
 * 16 кГц моно взяты не с потолка: Google всё равно приводит любой звук
 * к 16 кГц моно, так что отдавать больше — значит гонять по сети лишние
 * байты без всякой пользы. Токенов это не касается вовсе: они считаются
 * по длительности (32 на секунду), а не по весу файла.
 *
 * Нет ffmpeg — отправляем как есть. Это не «сломалось», а «повезёт с Opus»:
 * в образе ffmpeg стоит (Dockerfile), так что путь этот — для запуска бота
 * руками на машине без него.
 */
import { logger } from '../logger.js';
import { hasFfmpeg, runFfmpeg } from './ffmpeg.js';
import type { Attachment } from '../types.js';

/** Частота, к которой Google приводит любой присланный звук. */
const SAMPLE_RATE = 16_000;

/**
 * Потолок на перекодированный файл.
 *
 * Вложения уходят прямо в теле запроса, а там предел около 20 МБ на всё.
 * Обычному голосовому до него бесконечно далеко — но Telegram позволяет
 * скачать файл до 20 МБ, а это при опусовых 2–4 КБ/с больше часа записи,
 * и вот час в FLAC в запрос уже не поместится. Такую отправляем как есть:
 * оригинал заведомо маленький, и шанс с Opus лучше, чем гарантированный
 * отказ по размеру.
 */
const MAX_PREPARED_BYTES = 15 * 1024 * 1024;

/**
 * Приводит голосовое к формату, который Google принимает наверняка.
 *
 * Ошибку не бросает никогда: перекодировка — улучшение, а не условие работы.
 * Не вышла — отправим оригинал и запишем причину в лог.
 */
export async function prepareVoice(audio: Attachment): Promise<Attachment> {
  if (!hasFfmpeg()) return audio;

  try {
    const flac = await runFfmpeg(
      [
        '-i', 'pipe:0',
        // Видеодорожки у голосового нет, но кружочки и пересланные ролики
        // когда-нибудь могут прийти этим же путём — пусть отбрасывается.
        '-vn',
        '-ar', String(SAMPLE_RATE),
        '-ac', '1',
        '-c:a', 'flac',
        '-f', 'flac',
        'pipe:1',
      ],
      audio.data,
      `${audio.mimeType} → FLAC`,
    );

    if (flac.length > MAX_PREPARED_BYTES) {
      logger.warn('Перекодированное голосовое слишком велико для запроса, отправляю оригинал', {
        мб: Math.round(flac.length / 1024 / 1024),
      });
      return audio;
    }

    logger.debug('Голосовое перекодировано для модели', {
      было: `${Math.round(audio.data.length / 1024)} КБ (${audio.mimeType})`,
      стало: `${Math.round(flac.length / 1024)} КБ (audio/flac)`,
    });

    return { data: flac, mimeType: 'audio/flac' };
  } catch (error) {
    // Оригинал у нас на руках, так что худшее, что здесь может случиться, —
    // отказ Google по формату, то есть ровно то, что было бы и без ffmpeg.
    logger.warn('Не удалось перекодировать голосовое, отправляю как есть', {
      mime: audio.mimeType,
      error: error instanceof Error ? error.message : String(error),
    });
    return audio;
  }
}
